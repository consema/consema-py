class _Validator:
    """Input node budget accounting during validation (materialization.rs:
    497-520)."""

    def __init__(self, limits) -> None:
        self.nodes = 0
        self.limits = limits

    def step(self) -> None:
        self.nodes += 1
        if self.nodes > self.limits.max_input_nodes:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.RESOURCE_LIMIT,
                resource_name="input-nodes",
            )


@dataclass(frozen=True, slots=True)
class _ValueNode:
    """One validated value record with its kind semantics."""

    kind: str
    text: str = ""
    flag: bool = False
    elements: tuple[_ValueNode, ...] = ()
    entries: tuple[tuple[str, _ValueNode], ...] = ()
    expression: HclExpression | None = None
    expression_text: str = ""


@dataclass(frozen=True, slots=True)
class _BodyItem:
    """One validated body item."""

    kind: str
    name: str = ""
    value: _ValueNode | None = None
    block_type: str = ""
    labels: tuple[str, ...] = ()
    body: _Body | None = None


@dataclass(frozen=True, slots=True)
class _Body:
    """One validated body: ordered attributes and blocks."""

    items: tuple[_BodyItem, ...]


@dataclass(frozen=True, slots=True)
class _Record:
    """One validated `hcl.body@1` record."""

    body: _Body

    @classmethod
    def validate(
        cls, value: PortableValue, request: MaterializationRequest, analyzed: list[ValuePath]
    ) -> _Record:
        analyzed.append(ValuePath.root())
        if value.kind is not Kind.OBJECT:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.INVALID_REQUEST,
                detail="input record is not an object",
            )
        record_value = _field(value, "record", "input record is missing the record member")
        if record_value is None or record_value.kind is not Kind.STRING:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.INVALID_REQUEST,
                detail="input record is missing the record member",
            )
        if record_value.as_string() != BODY_RECORD:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.INVALID_REQUEST,
                detail="input record is not hcl.body@1",
            )
        tfvars = request.target_profile == ProfileId.new("hcl.tfvars", 1)
        validator = _Validator(request.limits)
        body = _validate_body(value, ValuePath.root(), validator, analyzed, tfvars, 0)
        return _Record(body=body)


def _field(value: PortableValue, name: str, missing_detail: str) -> PortableValue | None:
    for key, member in value.as_object():
        if key == name:
            return member
    raise HclMaterializationFailure(
        HclMaterializationFailureKind.INVALID_REQUEST, detail=missing_detail
    )


def _validate_body(
    value: PortableValue,
    path: ValuePath,
    validator: _Validator,
    analyzed: list[ValuePath],
    tfvars: bool,
    depth: int,
) -> _Body:
    if depth > validator.limits.max_depth:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.RESOURCE_LIMIT, resource_name="input-depth"
        )
    items_value = _field(value, "items", "input body record is missing the items member")
    if items_value.kind is not Kind.SEQUENCE:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.UNREPRESENTABLE,
            detail="body items must be a sequence",
        )
    items = items_value.as_sequence()
    out: list[_BodyItem] = []
    names: set[str] = set()
    for index, item in enumerate(items):
        item_path = path.child(ValuePathSegment(ValuePathSegmentKind.SEQUENCE_ELEMENT, index))
        validator.step()
        analyzed.append(item_path)
        if item.kind is not Kind.OBJECT:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.UNREPRESENTABLE,
                detail="body item is not an object",
            )
        kind_value = _field(item, "kind", "body item is missing the kind member")
        if kind_value.kind is not Kind.STRING:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.UNREPRESENTABLE,
                detail="body item kind is not a string",
            )
        kind = kind_value.as_string()
        if kind == "attribute":
            name_value = _field(item, "name", "attribute item is missing the name member")
            if name_value.kind is not Kind.STRING:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="attribute name is not a string",
                )
            name = name_value.as_string()
            if not _is_plain_identifier(name):
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="attribute name is not a valid identifier",
                )
            if name in names:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="duplicate attribute name in one body",
                )
            names.add(name)
            value_member = _field(item, "value", "attribute item is missing the value member")
            value_node = _validate_value(value_member, request_limits(validator), analyzed)
            out.append(_BodyItem(kind="attribute", name=name, value=value_node))
        elif kind == "block":
            if tfvars:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="block in tfvars target",
                )
            type_value = _field(item, "type", "block item is missing the type member")
            if type_value.kind is not Kind.STRING:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="block type is not a string",
                )
            block_type = type_value.as_string()
            if not _is_plain_identifier(block_type):
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="block type is not a valid identifier",
                )
            labels_value = _field(item, "labels", "block item is missing the labels member")
            if labels_value.kind is not Kind.SEQUENCE:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="block labels must be a sequence",
                )
            labels = []
            for label in labels_value.as_sequence():
                if label.kind is not Kind.STRING:
                    raise HclMaterializationFailure(
                        HclMaterializationFailureKind.UNREPRESENTABLE,
                        detail="block label is not a string",
                    )
                labels.append(label.as_string())
            body_member = _field(item, "body", "block item is missing the body member")
            body_path = item_path.child(ValuePathSegment(ValuePathSegmentKind.OBJECT_VALUE, "body"))
            nested = _validate_body(body_member, body_path, validator, analyzed, tfvars, depth + 1)
            out.append(
                _BodyItem(
                    kind="block",
                    block_type=block_type,
                    labels=tuple(labels),
                    body=nested,
                )
            )
        else:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.UNREPRESENTABLE,
                detail=f"unknown body item kind {kind!r}",
            )
    return _Body(items=tuple(out))


def request_limits(validator: _Validator):
    return validator.limits


def _validate_value(
    value: PortableValue, limits, analyzed: list[ValuePath]
) -> _ValueNode:
    if value.kind is Kind.OBJECT and _looks_like_expression_record(value):
        # The raw typed member form of a derived expression: the
        # `hcl.expression@1` record object itself (materialization.rs:61-64).
        return _validate_expression_record(value, limits)
    if value.kind is Kind.OBJECT and _looks_like_value_record(value):
        kind_value = _field(value, "kind", "value record is missing the kind member")
        kind = kind_value.as_string()
        if kind == "string":
            text_value = _field(value, "text", "string value is missing the text member")
            if text_value.kind is not Kind.STRING:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="string text is not a string",
                )
            return _ValueNode(kind="string", text=text_value.as_string())
        if kind == "integer":
            int_value = _field(value, "value", "integer value is missing the value member")
            if int_value.kind is not Kind.INTEGER:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="integer value is not an integer",
                )
            return _ValueNode(kind="integer", text=str(int_value.as_integer()))
        if kind == "real":
            real_value = _field(value, "value", "real value is missing the value member")
            return _ValueNode(kind="real", text=_real_spelling(real_value))
        if kind == "boolean":
            bool_value = _field(value, "value", "boolean value is missing the value member")
            if bool_value.kind is not Kind.BOOLEAN:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="boolean value is not a boolean",
                )
            return _ValueNode(kind="boolean", flag=bool_value.as_boolean())
        if kind == "null":
            return _ValueNode(kind="null")
        if kind == "tuple":
            elements_value = _field(value, "elements", "tuple value is missing the elements member")
            if elements_value.kind is not Kind.SEQUENCE:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="tuple elements are not a sequence",
                )
            elements = tuple(
                _validate_value(element, limits, analyzed)
                for element in elements_value.as_sequence()
            )
            return _ValueNode(kind="tuple", elements=elements)
        if kind == "object":
            entries_value = _field(value, "entries", "object value is missing the entries member")
            if entries_value.kind is not Kind.SEQUENCE:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="object entries are not a sequence",
                )
            entries = []
            for entry in entries_value.as_sequence():
                if entry.kind is not Kind.SEQUENCE or len(entry.as_sequence()) != 2:
                    raise HclMaterializationFailure(
                        HclMaterializationFailureKind.UNREPRESENTABLE,
                        detail="object entry is not a key/value pair",
                    )
                key, entry_value = entry.as_sequence()
                if key.kind is not Kind.STRING:
                    raise HclMaterializationFailure(
                        HclMaterializationFailureKind.UNREPRESENTABLE,
                        detail="object entry key is not a string",
                    )
                entries.append(
                    (
                        key.as_string(),
                        _validate_value(entry_value, limits, analyzed),
                    )
                )
            return _ValueNode(kind="object", entries=tuple(entries))
        if kind == "expression":
            expression_value = _field(
                value, "expression", "expression value is missing the expression member"
            )
            return _validate_expression_record(expression_value, limits)
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.UNREPRESENTABLE,
            detail=f"unknown value kind {kind!r}",
        )
    if value.kind is Kind.STRING:
        return _ValueNode(kind="string", text=value.as_string())
    if value.kind is Kind.INTEGER:
        return _ValueNode(kind="integer", text=str(value.as_integer()))
    if value.kind in (Kind.DECIMAL, Kind.BINARY_FLOAT64, Kind.BINARY_FLOAT32):
        return _ValueNode(kind="real", text=_real_spelling(value))
    if value.kind is Kind.BOOLEAN:
        return _ValueNode(kind="boolean", flag=value.as_boolean())
    if value.kind is Kind.NULL:
        return _ValueNode(kind="null")
    if value.kind is Kind.SEQUENCE:
        elements = tuple(
            _validate_value(element, limits, analyzed) for element in value.as_sequence()
        )
        return _ValueNode(kind="tuple", elements=elements)
    if value.kind is Kind.ENTRY_MAPPING:
        entries = []
        for key, entry_value in value.as_entry_mapping():
            if key.kind is not Kind.STRING:
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.UNREPRESENTABLE,
                    detail="object entry key is not a string",
                )
            entries.append((key.as_string(), _validate_value(entry_value, limits, analyzed)))
        return _ValueNode(kind="object", entries=tuple(entries))
    raise HclMaterializationFailure(
        HclMaterializationFailureKind.UNREPRESENTABLE,
        detail=f"unrepresentable value kind {value.kind.value}",
    )


def _looks_like_value_record(value: PortableValue) -> bool:
    names = {key for key, _ in value.as_object()}
    return "kind" in names


def _looks_like_expression_record(value: PortableValue) -> bool:
    names = {key for key, _ in value.as_object()}
    return "record" in names and "text" in names


def _real_spelling(value: PortableValue) -> str:
    if value.kind is Kind.DECIMAL:
        return render_decimal(value.as_decimal())
    if value.kind is Kind.BINARY_FLOAT64:
        spelling = _double_to_canonical_decimal(value.as_binary_float64())
        if spelling is None:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.UNREPRESENTABLE,
                detail="non-finite real payload",
            )
        return spelling
    spelling = _double_to_canonical_decimal(value.as_binary_float32())
    if spelling is None:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.UNREPRESENTABLE,
            detail="non-finite real payload",
        )
    return spelling


def _validate_expression_record(value: PortableValue, limits) -> _ValueNode:
    record_value = _field(value, "record", "expression record is missing the record member")
    if record_value.kind is not Kind.STRING or record_value.as_string() != EXPRESSION_RECORD:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.INVALID_REQUEST,
            detail="expression record is not hcl.expression@1",
        )
    kind_value = _field(value, "kind", "expression record is missing the kind member")
    text_value = _field(value, "text", "expression record is missing the text member")
    if kind_value.kind is not Kind.STRING or text_value.kind is not Kind.STRING:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.INVALID_REQUEST,
            detail="expression record members are not strings",
        )
    kind = kind_value.as_string()
    if kind not in _KIND_FAMILY_NAMES:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.INVALID_REQUEST,
            detail="expression kind spelling is not in the closed set",
        )
    text = text_value.as_string()
    if not text:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.INVALID_REQUEST,
            detail="expression text is empty",
        )
    ast = _promised_expression_parse(text, limits)
    if ast.kind.kind_family() != kind:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.INVALID_REQUEST,
            detail="expression kind does not match the parsed text",
        )
    fingerprint_value = None
    for key, member in value.as_object():
        if key == "fingerprint":
            fingerprint_value = member
    if fingerprint_value is not None:
        if fingerprint_value.kind is not Kind.STRING:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.INVALID_REQUEST,
                detail="expression fingerprint is not a string",
            )
        promised = structural_fingerprint_hex(ast)
        if fingerprint_value.as_string() != promised:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.INVALID_REQUEST,
                detail="expression fingerprint does not match",
            )
    return _ValueNode(kind="expression", expression=ast, expression_text=text)


def _promised_expression_parse(text: str, limits) -> HclExpression:
    """Parses one promised expression text standalone; the wrapper source
    is exactly `text.len() + 8` bytes (materialization.rs:1084-1120)."""
    source = f"{SENTINEL_ATTRIBUTE} = {text}\n".encode("utf-8")
    try:
        document = parse_document(source, HclProfile.NATIVE_V1, limits=_expression_limits(text, limits))
    except Exception:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.RESOURCE_LIMIT, resource_name="input-depth"
        ) from None
    if document.formation_status() is not FormationStatus.COMPLETE:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.INVALID_REQUEST,
            detail="expression text does not parse",
        )
    items = document.body.items
    if len(items) != 1:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.INVALID_REQUEST,
            detail="expression text does not parse",
        )
    attribute = items[0].as_attribute()
    if attribute is None or attribute.name != SENTINEL_ATTRIBUTE:
        raise HclMaterializationFailure(
            HclMaterializationFailureKind.INVALID_REQUEST,
            detail="expression text does not parse",
        )
    return attribute.expression


def _expression_limits(text: str, limits) -> HclParseLimits:
    from consema.document.limits import ParseLimits

    source = len(text.encode("utf-8")) + 8
    return HclParseLimits(
        common=ParseLimits(
            max_source_bytes=source,
            max_nesting_depth=limits.max_depth + 2,
            max_token_count=source * 2,
            max_node_count=source * 2,
            max_diagnostics=limits.max_report_entries,
        ),
        max_decoded_utf8_bytes=source * 3,
        max_decoded_scalars=source,
        max_body_depth=4,
        max_expression_depth=limits.max_depth + 2,
        max_template_depth=limits.max_depth + 2,
        max_attribute_count=8,
        max_block_count=8,
        max_label_count=8,
        max_body_item_count=16,
        max_identifier_len=source,
        max_string_len=source,
        max_number_digits=limits.max_output_bytes,
        max_template_len=source,
        max_template_interpolations=source,
        max_heredoc_lines=source,
        max_heredoc_bytes=source,
        max_tuple_elements=source,
        max_object_entries=source,
        max_for_extent=source,
        max_recovery_regions=limits.max_report_entries,
        max_error_regions=limits.max_report_entries,
        max_syntax_pieces=source * 2,
        max_report_events=limits.max_report_entries,
    )


