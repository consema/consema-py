class _Writer:
    """The canonical emitter: a bounded output String with checked appends
    (materialization.rs:1133-1171)."""

    def __init__(self, limits) -> None:
        self.out: list[str] = []
        self.total = 0
        self.limits = limits

    def push(self, text: str) -> None:
        self.total += len(text.encode("utf-8"))
        if self.total > self.limits.max_output_bytes:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.RESOURCE_LIMIT,
                resource_name="output-bytes",
            )
        self.out.append(text)

    def indent(self, depth: int) -> None:
        for _ in range(depth):
            self.push("  ")

    def push_quoted(self, text: str) -> None:
        self.push('"')
        self.push(escape_text(text))
        self.push('"')

    def finish(self) -> bytes:
        return "".join(self.out).encode("utf-8")


def _write_body(writer: _Writer, body: _Body, depth: int) -> None:
    for item in body.items:
        if item.kind == "attribute":
            writer.indent(depth)
            writer.push(item.name)
            writer.push(" = ")
            _write_value(writer, item.value, depth)
            writer.push("\n")
        else:
            writer.indent(depth)
            writer.push(item.block_type)
            for label in item.labels:
                writer.push(" ")
                writer.push_quoted(label)
            writer.push(" {\n")
            _write_body(writer, item.body, depth + 1)
            writer.indent(depth)
            writer.push("}\n")


def _write_value(writer: _Writer, value: _ValueNode, depth: int) -> None:
    kind = value.kind
    if kind == "string":
        writer.push_quoted(value.text)
    elif kind in ("integer", "real"):
        writer.push(value.text)
    elif kind == "boolean":
        writer.push("true" if value.flag else "false")
    elif kind == "null":
        writer.push("null")
    elif kind == "tuple":
        if not value.elements:
            writer.push("[]")
            return
        writer.push("[\n")
        last = len(value.elements) - 1
        for index, element in enumerate(value.elements):
            writer.indent(depth + 1)
            _write_value(writer, element, depth + 1)
            writer.push("\n" if index == last else ",\n")
        writer.indent(depth)
        writer.push("]")
    elif kind == "object":
        if not value.entries:
            writer.push("{}")
            return
        writer.push("{\n")
        last = len(value.entries) - 1
        for index, (key, entry_value) in enumerate(value.entries):
            writer.indent(depth + 1)
            _write_object_key(writer, key)
            writer.push(" = ")
            _write_value(writer, entry_value, depth + 1)
            writer.push("\n" if index == last else ",\n")
        writer.indent(depth)
        writer.push("}")
    else:
        writer.push(value.expression_text)


def _write_object_key(writer: _Writer, key: str) -> None:
    """One object key: bare for a plain identifier other than the
    contextual `for`, else quoted (materialization.rs:1255-1264)."""
    if _is_plain_identifier(key) and key != "for":
        writer.push(key)
    else:
        writer.push_quoted(key)


def _is_plain_identifier(text: str) -> bool:
    """Whether one text is a valid UAX #31 identifier with the frozen
    hyphen continuation and the underscore exclusion at the start (RFC
    0014 §4.1, §12 D-4; materialization.rs:1266-1278)."""
    if not text:
        return False
    first = text[0]
    if first == "_" or not is_identifier_start(first):
        return False
    for character in text[1:]:
        if not (is_identifier_continue(character) or character == "-"):
            return False
    return True


def _is_escaped_control(character: str) -> bool:
    value = ord(character)
    return value < 0x20 or 0x7F <= value <= 0x9F


def escape_text(text: str) -> str:
    """Escapes one string with the minimal deterministic escape set (RFC
    0014 §9): `\\n`, `\\r`, `\\t`, `\\"`, `\\\\`, `\\uNNNN` for control
    characters, and the `$${`/`%%{` doubling for the template openers
    (materialization.rs:1280-1333)."""
    out: list[str] = []
    index = 0
    while index < len(text):
        byte = text[index]
        if byte in ("$", "%"):
            run = 1
            while index + run < len(text) and text[index + run] == byte:
                run += 1
            doubled = index + run < len(text) and text[index + run] == "{"
            out.append(byte * (run + (1 if doubled else 0)))
            index += run
        else:
            if byte == '"':
                out.append('\\"')
            elif byte == "\\":
                out.append("\\\\")
            elif byte == "\n":
                out.append("\\n")
            elif byte == "\r":
                out.append("\\r")
            elif byte == "\t":
                out.append("\\t")
            elif _is_escaped_control(byte):
                out.append(f"\\u{ord(byte):04x}")
            else:
                out.append(byte)
            index += 1
    return "".join(out)


def render_decimal(decimal: Decimal) -> str:
    """Renders one normalized decimal as its plain canonical spelling: the
    coefficient digits with the exponent folded into the decimal point
    position, `"0"` for zero (RFC 0014 §9; materialization.rs:1341-1428)."""
    coefficient = decimal.coefficient
    if coefficient == 0:
        return "0"
    digits = str(coefficient)
    exponent = decimal.exponent
    if exponent == 0:
        return digits
    if exponent > 0:
        return digits + ("0" * exponent)
    fraction = -exponent
    signed = digits.startswith("-")
    magnitude = digits[1:] if signed else digits
    if fraction < len(magnitude):
        point = len(magnitude) - fraction
        out = "-" if signed else ""
        out += magnitude[:point] + "." + magnitude[point:]
        return out
    zeros = fraction - len(magnitude)
    out = "-" if signed else ""
    out += "0." + ("0" * zeros) + magnitude
    return out


def _double_to_canonical_decimal(bits: int) -> str | None:
    """Exact canonical decimal spelling of one binary64 datum; None for
    NaN and infinity, which the HCL number grammar cannot express
    (materialization.rs:1450-1494)."""
    if bits >> 63:
        sign = 1
    else:
        sign = 0
    exponent_bits = (bits >> 52) & 0x7FF
    fraction = bits & 0xFFFFFFFFFFFFF
    if exponent_bits == 0:
        if fraction == 0:
            return "0"
        mantissa = fraction
        exponent = -1074
    elif exponent_bits == 0x7FF:
        return None
    else:
        mantissa = fraction | 0x10000000000000
        exponent = exponent_bits - 1075
    if exponent >= 0:
        digits = str(mantissa << exponent)
    else:
        magnitude = -exponent
        digits = str(mantissa * (5**magnitude))
        digits = _place_decimal_point(digits, magnitude)
    canonical = canonical_decimal(digits)
    if canonical is None:
        return None
    if sign and canonical != "0":
        canonical = "-" + canonical
    return canonical


def _place_decimal_point(digits: str, fraction: int) -> str:
    if fraction < len(digits):
        point = len(digits) - fraction
        return digits[:point] + "." + digits[point:]
    return "0." + ("0" * (fraction - len(digits))) + digits


