class _Target(enum.Enum):
    """The canonical materialization target (materialization.rs:194-201)."""

    NATIVE = "native"
    TFVARS = "tfvars"


def materialize(
    value: PortableValue, request: MaterializationRequest
) -> MaterializationResult:
    """Materializes one `hcl.body@1` record into a new canonical HCL
    document (RFC 0014 §9; materialization.rs:213-226)."""
    analyzed: list[ValuePath] = []
    try:
        complete = _materialize_complete(value, request, analyzed)
    except HclMaterializationFailure as failure:
        return FailedMaterializationAttempt(
            failure=_shared_failure(failure),
            report=MaterializationReport(),
            analyzed_input_paths=tuple(analyzed),
        )
    return complete


def _shared_failure(failure: HclMaterializationFailure):
    """The shared MaterializationFailure surface consumed by the failure
    algebra (RFC 0004 §7)."""
    from consema.document.materialization import (
        MaterializationFailure,
        MaterializationFailureKind,
    )

    kind = {
        HclMaterializationFailureKind.UNSUPPORTED_PROFILE: MaterializationFailureKind.UNSUPPORTED_PROFILE,
        HclMaterializationFailureKind.UNSUPPORTED_STYLE: MaterializationFailureKind.UNSUPPORTED_STYLE,
        HclMaterializationFailureKind.UNSUPPORTED_ENCODING: MaterializationFailureKind.UNSUPPORTED_ENCODING,
        HclMaterializationFailureKind.UNSUPPORTED_NEWLINE: MaterializationFailureKind.UNSUPPORTED_NEWLINE,
        HclMaterializationFailureKind.RESOURCE_LIMIT: MaterializationFailureKind.RESOURCE_LIMIT,
        HclMaterializationFailureKind.UNREPRESENTABLE: MaterializationFailureKind.UNREPRESENTABLE,
        HclMaterializationFailureKind.INVALID_REQUEST: MaterializationFailureKind.INVALID_REQUEST,
        HclMaterializationFailureKind.FORMATION_FAILED: MaterializationFailureKind.FORMATION_FAILED,
    }.get(failure.kind, MaterializationFailureKind.INVALID_REQUEST)
    return MaterializationFailure(kind, name=failure.resource_name, detail=failure.detail)


def materialization_failure_code(failure) -> str:
    """The suite-published failure code of one shared MaterializationFailure
    (RFC 0014 §9; crates/consema-conformance/src/hcl_v1.rs:1611-1616):
    Unrepresentable maps to hcl.materialization.unrepresentable@1,
    ResourceLimit to hcl.materialization.resource-limit@1, InvalidRequest
    to the published spelling "invalid-record"."""
    from consema.document.materialization import MaterializationFailureKind

    if failure.kind is MaterializationFailureKind.UNREPRESENTABLE:
        return "hcl.materialization.unrepresentable@1"
    if failure.kind is MaterializationFailureKind.RESOURCE_LIMIT:
        return "hcl.materialization.resource-limit@1"
    if failure.kind is MaterializationFailureKind.INVALID_REQUEST:
        return "invalid-record"
    return failure.code


def _materialize_complete(
    value: PortableValue,
    request: MaterializationRequest,
    analyzed: list[ValuePath],
) -> CompleteMaterialization:
    target = _validate_request(request)
    limits = request.limits
    record = _Record.validate(value, request, analyzed)
    writer = _Writer(limits)
    _write_body(writer, record.body, 0)
    bytes_ = writer.finish()
    profile = (
        HclProfile.TFVARS_V1 if target is _Target.TFVARS else HclProfile.NATIVE_V1
    )
    document = parse_document(bytes_, profile, limits=_parse_limits(limits))
    if document.formation_status() is not FormationStatus.COMPLETE:
        raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
    provenance = _verify_closure(record, document, limits)
    return CompleteMaterialization(
        document=document,
        fidelity=MaterializationFidelity.EXACT,
        report=MaterializationReport(),
        provenance=provenance,
    )


def _validate_request(request: MaterializationRequest) -> _Target:
    """Validates the request against the frozen style contract (RFC 0014
    §9; materialization.rs:266-285)."""
    profile = request.target_profile
    style = request.style
    if profile.id == "hcl.native" and profile.version == 1 and style.id == STYLE_CANONICAL and style.version == 1:
        target = _Target.NATIVE
    elif profile.id == "hcl.tfvars" and profile.version == 1 and style.id == STYLE_CANONICAL and style.version == 1:
        target = _Target.TFVARS
    elif profile.id not in ("hcl.native", "hcl.tfvars") or profile.version != 1:
        raise HclMaterializationFailure(HclMaterializationFailureKind.UNSUPPORTED_PROFILE)
    else:
        raise HclMaterializationFailure(HclMaterializationFailureKind.UNSUPPORTED_STYLE)
    if request.encoding != SourceEncoding.utf8():
        raise HclMaterializationFailure(HclMaterializationFailureKind.UNSUPPORTED_ENCODING)
    if request.newline is not NewlinePolicy.LF:
        raise HclMaterializationFailure(HclMaterializationFailureKind.UNSUPPORTED_NEWLINE)
    return target


