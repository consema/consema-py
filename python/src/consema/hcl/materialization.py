"""Canonical `hcl.canonical-document@1` materialization (RFC 0014 §9).

Materialization consumes one validated `hcl.body@1` record and creates a
new `hcl.native@1` or `hcl.tfvars@1` Document. It is not a formatter for an
existing source: the input is the projected body record, the output is a
new snapshot whose complete native model equals the promised input
semantics.

The input must be an Object record `{ "record": "hcl.body@1", "items":
[<item>, ...] }`; an item is an Object with a string `kind`
(`attribute`/`block`). A value record is an Object with a string `kind`
(string/integer/real/boolean/null/tuple/object/expression), and the RFC
0014 §8.2 typed member itself is also accepted as the attribute `value`
(raw string, integer, real, boolean, null, tuple, object PortableValue or
an `hcl.expression@1` record object). Attribute names and block types must
be valid UAX #31 identifiers; a body with two attributes of the same name
is unrepresentable, because the per-body duplicate-attribute rule of RFC
0014 §3 admits no Complete document with duplicates.

The style emits UTF-8 without BOM with LF line endings, two-space
indentation per body nesting level, `name = value` attributes, block
headers as `type "label" {`, minimal deterministic string escapes, numbers
in canonical decimal spelling, one-item-per-line constructor layout with
empty constructors single-line, `=` object keys, always-quoted labels, and
`hcl.expression@1` values emitting their canonical text verbatim.

Every style validates the complete input before proportional allocation,
encodes, reparses the exact generated bytes under the promised Profile, and
compares the reparsed native model to the promised input semantics —
numbers by canonical-decimal value equality, everything else by structural
equality, `hcl.expression@1` values by structural equality plus
fingerprint equality (RFC 0014 §6, §9). Failure returns no target
Document, partial bytes, or partial provenance.

Authority (language-neutral first; Rust only for byte/registry
arbitration): crates/consema-hcl/src/materialization.rs — the record
contract materialization.rs:9-103, request validation
materialization.rs:266-285, the canonical layout materialization.rs:105-121
and writer materialization.rs:1133-1333, decimal rendering
materialization.rs:1341-1494, the expression promise
materialization.rs:1084-1120, the closure walk materialization.rs:1770-...,
and the failure mapping materialization.rs:124-137.
"""

