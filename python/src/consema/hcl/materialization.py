def _verify_closure(record: _Record, document: HclDocument, limits) -> MaterializationProvenanceMap:
    entries: list[MaterializationProvenanceEntry] = []
    units = 0

    def push_origin(input_location: MaterializationInputLocation, origin: MaterializedOrigin) -> None:
        nonlocal units
        units += 1
        if units > limits.max_provenance_entries:
            raise HclMaterializationFailure(
                HclMaterializationFailureKind.RESOURCE_LIMIT,
                resource_name="provenance-entries",
            )
        entries.append(
            MaterializationProvenanceEntry(input=input_location, outputs=(origin,))
        )

    def origin(node: NodeRef, span: Span) -> MaterializedOrigin:
        return MaterializedOrigin(
            snapshot=document.snapshot_identity(),
            node=node,
            span=span,
            relation=MaterializationRelation.DIRECT,
        )

    def root_path() -> ValuePath:
        return ValuePath.root()

    push_origin(
        MaterializationInputLocation.value(root_path()),
        origin(
            document.authority.node_ref(0, _document_role()),
            document.authority.span(0, len(document.source.bytes())),
        ),
    )

    def walk_body(record_body: _Body, native_body, body_path: ValuePath) -> None:
        if len(record_body.items) != len(native_body.items):
            raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
        for index, (record_item, native_item) in enumerate(zip(record_body.items, native_body.items)):
            item_path = body_path.child(
                ValuePathSegment(ValuePathSegmentKind.SEQUENCE_ELEMENT, index)
            )
            if record_item.kind == "attribute":
                attribute = native_item.as_attribute()
                if attribute is None or attribute.name != record_item.name:
                    raise HclMaterializationFailure(
                        HclMaterializationFailureKind.FORMATION_FAILED
                    )
                push_origin(
                    MaterializationInputLocation.value(item_path),
                    origin(
                        document.node_ref(attribute),
                        document.authority.span(
                            attribute.name_span.start_byte,
                            attribute.expression.span.end_byte,
                        ),
                    ),
                )
                value_path = item_path.child(
                    ValuePathSegment(ValuePathSegmentKind.OBJECT_VALUE, "value")
                )
                _verify_value(record_item.value, attribute.expression, value_path, document)
                push_origin(
                    MaterializationInputLocation.value(value_path),
                    origin(
                        document.node_ref(attribute.expression),
                        attribute.expression.span,
                    ),
                )
            else:
                block = native_item.as_block()
                if (
                    block is None
                    or block.block_type != record_item.block_type
                    or tuple(label.text for label in block.labels) != record_item.labels
                ):
                    raise HclMaterializationFailure(
                        HclMaterializationFailureKind.FORMATION_FAILED
                    )
                push_origin(
                    MaterializationInputLocation.value(item_path),
                    origin(document.node_ref(block), block.span),
                )
                for label in block.labels:
                    push_origin(
                        MaterializationInputLocation.value(item_path),
                        origin(document.node_ref(label), label.span),
                    )
                body_path_nested = item_path.child(
                    ValuePathSegment(ValuePathSegmentKind.OBJECT_VALUE, "body")
                )
                walk_body(record_item.body, block.body, body_path_nested)

    def _verify_value(
        promised: _ValueNode,
        native: HclExpression,
        path: ValuePath,
        document: HclDocument,
    ) -> None:
        kind = promised.kind
        if kind in ("integer", "real"):
            if native.kind.name is not HclExpressionKindName.NUMBER:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
            if native.kind.payload.canonical_decimal != promised.text:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
            if kind == "integer" and "." in promised.text:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
            if kind == "real" and "." not in promised.text:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
        elif kind == "string":
            if not is_literal_complete(native):
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
            literal = literal_value(native)
            if literal.kind != "string" or literal.text != promised.text:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
        elif kind == "boolean":
            if native.kind.name is not HclExpressionKindName.BOOLEAN or native.kind.payload != promised.flag:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
        elif kind == "null":
            if native.kind.name is not HclExpressionKindName.NULL:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
        elif kind == "tuple":
            if native.kind.name is not HclExpressionKindName.TUPLE:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
            elements = native.kind.payload
            if len(elements) != len(promised.elements):
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
            for index, (promised_element, native_element) in enumerate(zip(promised.elements, elements)):
                child_path = path.child(
                    ValuePathSegment(ValuePathSegmentKind.SEQUENCE_ELEMENT, index)
                )
                _verify_value(promised_element, native_element, child_path, document)
        elif kind == "object":
            if native.kind.name is not HclExpressionKindName.OBJECT:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
            entries = native.kind.payload
            if len(entries) != len(promised.entries):
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
            for index, ((promised_key, promised_value), native_entry) in enumerate(
                zip(promised.entries, entries)
            ):
                actual_key = _native_key_text(native_entry.key)
                if actual_key != promised_key:
                    raise HclMaterializationFailure(
                        HclMaterializationFailureKind.FORMATION_FAILED
                    )
                child_path = path.child(
                    ValuePathSegment(ValuePathSegmentKind.ENTRY_VALUE, index)
                )
                _verify_value(promised_value, native_entry.value, child_path, document)
        else:  # expression
            if native != promised.expression:
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
            if structural_fingerprint(native) != structural_fingerprint(promised.expression):
                raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)

    walk_body(record.body, document.body, root_path())
    return MaterializationProvenanceMap.new(entries, document.snapshot_identity(), limits)


def _native_key_text(key) -> str:
    """The canonical string spelling of one native object key, exactly as
    the canonical emitter renders it (materialization.rs:1255-1264)."""
    if key.kind == "identifier":
        return key.name or ""
    if key.kind == "number" and key.number is not None:
        return key.number.canonical_decimal
    if key.kind == "template" and key.template is not None:
        text = ""
        for part in key.template.parts:
            if part.kind != "literal":
                raise HclMaterializationFailure(
                    HclMaterializationFailureKind.FORMATION_FAILED
                )
            text += part.text
        return text
    if key.kind == "paren" and key.inner is not None:
        if not is_literal_complete(key.inner):
            raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
        literal = literal_value(key.inner)
        if literal.kind in ("integer", "real", "string"):
            return literal.text
        if literal.kind == "boolean":
            return "true" if literal.flag else "false"
        if literal.kind == "null":
            return "null"
        raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)
    raise HclMaterializationFailure(HclMaterializationFailureKind.FORMATION_FAILED)


def _document_role():
    from consema.document.structural import NodeRole

    return NodeRole.HCL_DOCUMENT
