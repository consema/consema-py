class _PrefixTable:
    """Deterministic generated-prefix assignment by first-encounter order
    (materialization.rs:502-526)."""

    __slots__ = ("entries", "next")

    def __init__(self) -> None:
        self.entries: dict[str, str] = {}
        self.next = 0

    def prefix_for(self, namespace: str, default: str | None) -> str:
        if namespace == default:
            return ""
        if namespace == XML_NAMESPACE_URI:
            return "xml"
        prefix = self.entries.get(namespace)
        if prefix is not None:
            return prefix
        self.next += 1
        prefix = f"ns{self.next}"
        self.entries[namespace] = prefix
        return prefix


