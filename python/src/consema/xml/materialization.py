class _Writer:
    __slots__ = ("limits", "input_nodes", "output", "prefixes", "scope", "items")

    def __init__(self, limits: MaterializationLimits) -> None:
        self.limits = limits
        self.input_nodes = 0
        self.output = bytearray()
        self.prefixes = _PrefixTable()
        self.scope: list[tuple[str | None, str]] = []
        self.items: list[_InputItem] = []

    def step(self) -> None:
        self.input_nodes += 1
        if self.input_nodes > self.limits.max_input_nodes:
            raise MaterializationFailure(
                MaterializationFailureKind.RESOURCE_LIMIT, name="input-nodes"
            )

    def push(self, data: bytes) -> None:
        self.output.extend(data)
        if len(self.output) > self.limits.max_output_bytes:
            raise MaterializationFailure(
                MaterializationFailureKind.RESOURCE_LIMIT, name="output-bytes"
            )

    def spelling_prefix(self, uri: str | None) -> str | None:
        """Spelling prefix for one expanded namespace (materialization.rs:
        601-621). ``None`` means the URI is not bound in scope and a
        declaration must be generated."""
        if uri is None:
            return ""
        if uri == XML_NAMESPACE_URI:
            return "xml"
        for prefix, bound in reversed(self.scope):
            if prefix is None and bound == uri:
                return ""
        for prefix, bound in reversed(self.scope):
            if prefix is not None and bound == uri:
                return prefix
        return None

    def push_escaped_text(self, text: str) -> None:
        """Materialization.rs:623-634: ``&`` and ``<`` are escaped."""
        for character in text:
            if character == "&":
                self.push(b"&amp;")
            elif character == "<":
                self.push(b"&lt;")
            else:
                self.push(character.encode("utf-8"))

    def push_escaped_attribute(self, text: str) -> None:
        """Materialization.rs:636-648: ``&``, ``<``, and ``"`` are escaped."""
        for character in text:
            if character == "&":
                self.push(b"&amp;")
            elif character == "<":
                self.push(b"&lt;")
            elif character == '"':
                self.push(b"&quot;")
            else:
                self.push(character.encode("utf-8"))

    def emit_document(self, input_record: _Record, request: MaterializationRequest) -> None:
        """materialization.rs:650-715."""
        self.step()
        if input_record.declaration is not None:
            declaration = input_record.declaration
            self.items.append(_InputItem(_InputItemKind.DECLARATION, declaration.path))
            self.push(b'<?xml version="')
            self.push_escaped_attribute(declaration.version)
            self.push(b'"')
            declared_encoding = declaration.encoding
            if declared_encoding is None and request.encoding.kind in (
                SourceEncodingKind.UTF16LE,
                SourceEncodingKind.UTF16BE,
            ):
                declared_encoding = "UTF-16"
            if declared_encoding is not None:
                self.push(b' encoding="')
                self.push_escaped_attribute(declared_encoding)
                self.push(b'"')
            if declaration.standalone is not None:
                self.push(b' standalone="yes"' if declaration.standalone else b' standalone="no"')
            self.push(b"?>")
        if input_record.entities:
            self.push(b"<!DOCTYPE ")
            root_prefix = self.spelling_prefix(input_record.root.namespace)
            if root_prefix is None:
                raise MaterializationFailure(
                    MaterializationFailureKind.UNREPRESENTABLE, name="doctype-name"
                )
            doctype_name = (
                input_record.root.local
                if root_prefix == ""
                else f"{root_prefix}:{input_record.root.local}"
            )
            self.push(doctype_name.encode("utf-8"))
            self.push(b" [")
            for entity in input_record.entities:
                self.items.append(_InputItem(_InputItemKind.ENTITY, entity.path))
                self.push(b"<!ENTITY ")
                self.push(entity.name.encode("utf-8"))
                self.push(b' "')
                self.push_escaped_attribute(entity.replacement)
                self.push(b'">')
            self.push(b"]>")
        self.emit_element(input_record.root, 0)
        self.push(request.newline.bytes)

    def emit_element(self, element: _ElementRecord, depth: int) -> None:
        """materialization.rs:717-899."""
        self.step()
        if depth > self.limits.max_depth:
            raise MaterializationFailure(
                MaterializationFailureKind.RESOURCE_LIMIT, name="input-depth"
            )
        self.items.append(_InputItem(_InputItemKind.ELEMENT, element.path))
        scope_len = len(self.scope)
        for prefix, uri in element.namespaces:
            self.scope.append((prefix, uri))
        element_prefix = self.spelling_prefix(element.namespace)
        if element_prefix is None:
            # Unbound URI in a hand-built record: declare a generated
            # default namespace on this element.
            uri = element.namespace or XML_NAMESPACE_URI
            if uri == XML_NAMESPACE_URI:
                element_prefix = "xml"
            else:
                self.push(b"<")
                self.push(element.local.encode("utf-8"))
                self.push(b' xmlns="')
                self.push_escaped_attribute(uri)
                self.push(b'"')
                self.scope.append((None, uri))
                self.items.append(_InputItem(_InputItemKind.NAMESPACE_BINDING, element.path))
                element_prefix = ""
        self.push(b"<")
        if element_prefix == "":
            self.push(element.local.encode("utf-8"))
        else:
            self.push(element_prefix.encode("utf-8"))
            self.push(b":")
            self.push(element.local.encode("utf-8"))
        for prefix, uri in element.namespaces:
            self.items.append(_InputItem(_InputItemKind.NAMESPACE_BINDING, element.path))
            if prefix is not None:
                self.push(b" xmlns:")
                self.push(prefix.encode("utf-8"))
                self.push(b'="')
                self.push_escaped_attribute(uri)
                self.push(b'"')
            else:
                self.push(b' xmlns="')
                self.push_escaped_attribute(uri)
                self.push(b'"')
        for attribute in element.attributes:
            self.items.append(_InputItem(_InputItemKind.ATTRIBUTE, attribute.path))
            attribute_prefix = self.spelling_prefix(attribute.namespace)
            if attribute_prefix is None:
                uri = attribute.namespace or XML_NAMESPACE_URI
                generated = self.prefixes.prefix_for(uri, None)
                self.push(b" xmlns:")
                self.push(generated.encode("utf-8"))
                self.push(b'="')
                self.push_escaped_attribute(uri)
                self.push(b'"')
                self.scope.append((generated, uri))
                self.items.append(_InputItem(_InputItemKind.NAMESPACE_BINDING, attribute.path))
                attribute_prefix = generated
            self.push(b" ")
            if attribute_prefix == "":
                self.push(attribute.local.encode("utf-8"))
            else:
                self.push(attribute_prefix.encode("utf-8"))
                self.push(b":")
                self.push(attribute.local.encode("utf-8"))
            self.push(b'="')
            self.push_escaped_attribute(attribute.value)
            self.push(b'"')
        if not element.content:
            self.push(b"/>")
            del self.scope[scope_len:]
            return
        self.push(b">")
        for item in element.content:
            if item.kind is _ContentKind.ELEMENT:
                assert item.element is not None
                self.emit_element(item.element, depth + 1)
            elif item.kind is _ContentKind.TEXT:
                self.items.append(_InputItem(_InputItemKind.TEXT, item.path))
                for fragment in item.fragments:
                    self.items.append(_InputItem(_InputItemKind.FRAGMENT, item.path))
                    if fragment.kind is _FragmentKind.LITERAL:
                        self.push_escaped_text(fragment.text or "")
                    elif fragment.kind is _FragmentKind.CHARACTER_REFERENCE:
                        self.push(f"&#{ord(fragment.resolved)};".encode("utf-8"))
                    else:
                        self.push(b"&")
                        self.push((fragment.name or "").encode("utf-8"))
                        self.push(b";")
            elif item.kind is _ContentKind.CDATA:
                self.items.append(_InputItem(_InputItemKind.CDATA, item.path))
                if "]]>" in (item.text or ""):
                    raise MaterializationFailure(
                        MaterializationFailureKind.UNREPRESENTABLE, name="cdata-text"
                    )
                self.push(b"<![CDATA[")
                self.push((item.text or "").encode("utf-8"))
                self.push(b"]]>")
            elif item.kind is _ContentKind.COMMENT:
                self.items.append(_InputItem(_InputItemKind.COMMENT, item.path))
                if "--" in (item.text or "") or (item.text or "").endswith("-"):
                    raise MaterializationFailure(
                        MaterializationFailureKind.UNREPRESENTABLE, name="comment-text"
                    )
                self.push(b"<!--")
                self.push((item.text or "").encode("utf-8"))
                self.push(b"-->")
            else:
                self.items.append(
                    _InputItem(_InputItemKind.PROCESSING_INSTRUCTION, item.path)
                )
                if (item.target or "").lower() == "xml" or "?>" in (item.content or ""):
                    raise MaterializationFailure(
                        MaterializationFailureKind.UNREPRESENTABLE, name="processing-instruction"
                    )
                self.push(b"<?")
                self.push((item.target or "").encode("utf-8"))
                if item.content is not None:
                    self.push(b" ")
                    self.push(item.content.encode("utf-8"))
                self.push(b"?>")
        self.push(b"</")
        if element_prefix == "":
            self.push(element.local.encode("utf-8"))
        else:
            self.push(element_prefix.encode("utf-8"))
            self.push(b":")
            self.push(element.local.encode("utf-8"))
        self.push(b">")
        del self.scope[scope_len:]


