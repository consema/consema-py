@dataclass(frozen=True, slots=True)
class _OutputItem:
    node: NodeRef
    span: Span
    relation: MaterializationRelation


def _verify_closure(
    input_record: _Record,
    document: Document,
    items: list[_InputItem],
    limits: MaterializationLimits,
) -> MaterializationProvenanceMap:
    """Walks the input record and the reparsed document in lockstep and
    pairs every recorded input location with its exact output origin
    (materialization.rs:912-1014)."""
    outputs: list[_OutputItem] = []
    root = document.root()
    if root is None:
        raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
    # Declaration closure.
    if input_record.declaration is not None:
        reparsed_declaration = document.declaration()
        if reparsed_declaration is None:
            raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
        if (
            reparsed_declaration.version != input_record.declaration.version
            or (reparsed_declaration.standalone[1] if reparsed_declaration.standalone else None)
            != input_record.declaration.standalone
        ):
            raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
    elif document.declaration() is not None:
        raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
    # Entity closure.
    reparsed_doctype = document.doctype()
    if reparsed_doctype is not None:
        reparsed_entities = reparsed_doctype.entities
        if len(reparsed_entities) != len(input_record.entities) or any(
            reparsed.name != declared.name or reparsed.replacement != declared.replacement
            for reparsed, declared in zip(reparsed_entities, input_record.entities)
        ):
            raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
    elif input_record.entities:
        raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
    if input_record.declaration is not None:
        outputs.append(
            _OutputItem(
                node=document.node_ref(1, NodeRole.XML_DECLARATION),
                span=document.declaration().span,
                relation=MaterializationRelation.DIRECT,
            )
        )
    if reparsed_doctype is not None:
        for entity in reparsed_doctype.entities:
            outputs.append(
                _OutputItem(
                    node=document.node_ref(2, NodeRole.XML_DOCTYPE),
                    span=entity.span,
                    relation=MaterializationRelation.DIRECT,
                )
            )
    context = _ClosureContext(document, outputs, limits)
    context.element(input_record.root, root)
    if len(outputs) != len(items):
        raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
    entries: list[MaterializationProvenanceEntry] = []
    for item, output in zip(items, outputs):
        location = item.location()
        origin = MaterializedOrigin(
            snapshot=document.snapshot_identity(),
            node=output.node,
            span=output.span,
            relation=output.relation,
        )
        if entries and entries[-1].input == location:
            last = entries[-1]
            entries[-1] = MaterializationProvenanceEntry(
                input=last.input, outputs=last.outputs + (origin,)
            )
            continue
        entries.append(
            MaterializationProvenanceEntry(input=location, outputs=(origin,))
        )
    return MaterializationProvenanceMap.new(entries, document.snapshot_identity(), limits)


class _ClosureContext:
    __slots__ = ("document", "outputs", "limits")

    def __init__(self, document: Document, outputs: list[_OutputItem], limits) -> None:
        self.document = document
        self.outputs = outputs
        self.limits = limits

    def push(self, node: NodeRef, span: Span, relation: MaterializationRelation) -> None:
        if len(self.outputs) >= self.limits.max_provenance_entries:
            raise MaterializationFailure(
                MaterializationFailureKind.RESOURCE_LIMIT, name="provenance-entries"
            )
        self.outputs.append(_OutputItem(node=node, span=span, relation=relation))

    def element(self, input_element: _ElementRecord, element) -> None:
        """One element closure walk (materialization.rs:1040-1209)."""
        self.push(element.node_ref(), element.span(), MaterializationRelation.DIRECT)
        expanded = element.expanded()
        if expanded is None:
            raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
        name_matches = (
            input_element.namespace is not None
            and expanded.namespace is not None
            and input_element.namespace == expanded.namespace
        ) or (input_element.namespace is None and expanded.namespace is None)
        if not name_matches or expanded.local != input_element.local:
            raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
        for binding in element.namespace_bindings():
            self.push(
                self.document.node_ref(binding.ordinal, NodeRole.XML_NAMESPACE_BINDING),
                binding.span,
                MaterializationRelation.GENERATED,
            )
        attributes = element.attributes()
        if len(attributes) != len(input_element.attributes):
            raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
        for input_attribute, attribute in zip(input_element.attributes, attributes):
            self.push(
                self.document.node_ref(attribute.ordinal, NodeRole.XML_ATTRIBUTE),
                attribute.span,
                MaterializationRelation.DIRECT,
            )
            if attribute.expanded is None:
                raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
            attr_name_matches = (
                input_attribute.namespace is not None
                and attribute.expanded.namespace is not None
                and input_attribute.namespace == attribute.expanded.namespace
            ) or (input_attribute.namespace is None and attribute.expanded.namespace is None)
            if (
                not attr_name_matches
                or attribute.expanded.local != input_attribute.local
                or attribute.normalized_value != input_attribute.value
            ):
                raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
        children = element.children()
        if len(children) != len(input_element.content):
            raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
        for child, input_item in zip(children, input_element.content):
            child_element = (
                XmlElement(self.document, child.data.index)
                if child.kind.value == "element"
                else None
            )
            if child_element is not None and input_item.kind is _ContentKind.ELEMENT:
                assert input_item.element is not None
                self.element(input_item.element, child_element)
            elif input_item.kind is _ContentKind.TEXT:
                if child.kind.value != "text":
                    raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
                text = child.data
                self.push(
                    self.document.node_ref(text.ordinal, NodeRole.XML_TEXT),
                    text.span,
                    MaterializationRelation.DIRECT,
                )
                semantic: list[str] = []
                for fragment in input_item.fragments:
                    if fragment.kind is _FragmentKind.LITERAL:
                        semantic.append(_normalize_line_ends(fragment.text or ""))
                    elif fragment.kind is _FragmentKind.CHARACTER_REFERENCE:
                        semantic.append(fragment.resolved or "")
                    else:
                        semantic.append(_normalize_line_ends(fragment.resolved or ""))
                    first_span = (
                        text.fragments[0].span if text.fragments else text.span
                    )
                    self.push(
                        self.document.node_ref(text.ordinal, NodeRole.XML_ENTITY_REFERENCE),
                        first_span,
                        MaterializationRelation.DIRECT,
                    )
                if text_semantic(text) != "".join(semantic):
                    raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
            elif input_item.kind is _ContentKind.CDATA:
                if child.kind.value != "cdata":
                    raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
                cdata = child.data
                self.push(
                    self.document.node_ref(cdata.ordinal, NodeRole.XML_CDATA),
                    cdata.span,
                    MaterializationRelation.DIRECT,
                )
                if cdata.text != input_item.text:
                    raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
            elif input_item.kind is _ContentKind.COMMENT:
                if child.kind.value != "comment":
                    raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
                comment = child.data
                self.push(
                    self.document.node_ref(comment.ordinal, NodeRole.XML_COMMENT),
                    comment.span,
                    MaterializationRelation.DIRECT,
                )
                if comment.text != input_item.text:
                    raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
            elif input_item.kind is _ContentKind.PROCESSING_INSTRUCTION:
                if child.kind.value != "processing-instruction":
                    raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
                pi = child.data
                self.push(
                    self.document.node_ref(pi.ordinal, NodeRole.XML_PROCESSING_INSTRUCTION),
                    pi.span,
                    MaterializationRelation.DIRECT,
                )
                if pi.target != input_item.target or (
                    pi.content[1] if pi.content is not None else None
                ) != input_item.content:
                    raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
            else:
                raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)


def _normalize_line_ends(text: str) -> str:
    """XML 1.0 line-end normalization for one fragment (materialization.rs:
    1212-1226)."""
    output: list[str] = []
    index = 0
    while index < len(text):
        character = text[index]
        if character == "\r":
            output.append("\n")
            if index + 1 < len(text) and text[index + 1] == "\n":
                index += 1
        else:
            output.append(character)
        index += 1
    return "".join(output)
