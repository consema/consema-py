@dataclass(frozen=True, slots=True)
class _Record:
    declaration: _DeclarationRecord | None
    entities: tuple[_EntityRecord, ...]
    root: _ElementRecord

    @classmethod
    def validate(cls, value: PortableValue) -> _Record:
        """Validates one complete ``xml.element-tree@1`` value
        (materialization.rs:238-304)."""
        record = _expect_string_field(value, "record", ValuePath.root())
        if record != "xml.element-tree@1":
            raise MaterializationFailure(
                MaterializationFailureKind.INVALID_REQUEST,
                detail="input record is not xml.element-tree@1",
            )
        root_path = ValuePath.root().child(ValuePathSegment.object_value("root"))
        root_value = _expect_object_field(value, "root", root_path)
        declaration = None
        declaration_path = ValuePath.root().child(ValuePathSegment.object_value("declaration"))
        declaration_value = _optional_object_field(value, "declaration")
        if declaration_value is not None:
            version = _expect_string_field(declaration_value, "version", declaration_path)
            if version != "1.0":
                raise MaterializationFailure(
                    MaterializationFailureKind.UNREPRESENTABLE,
                    name="declaration-version",
                )
            declaration = _DeclarationRecord(
                version=version,
                encoding=_optional_string_field(declaration_value, "encoding", declaration_path),
                standalone=_optional_boolean_field(declaration_value, "standalone", declaration_path),
                path=declaration_path,
            )
        entities: list[_EntityRecord] = []
        entities_path = ValuePath.root().child(ValuePathSegment.object_value("entities"))
        entities_value = _optional_sequence_field(value, "entities")
        if entities_value is not None:
            for index, entity in enumerate(entities_value):
                entity_path = entities_path.child(ValuePathSegment.sequence_element(index))
                name = _expect_string_field(entity, "name", entity_path)
                replacement = _expect_string_field(entity, "replacement", entity_path)
                if "<" in replacement:
                    raise MaterializationFailure(
                        MaterializationFailureKind.UNREPRESENTABLE,
                        name="entity-replacement",
                    )
                entities.append(_EntityRecord(name=name, replacement=replacement, path=entity_path))
        root = _ElementRecord.validate(root_value, root_path)
        return _Record(declaration=declaration, entities=tuple(entities), root=root)


def _ElementRecord_validate(value: PortableValue, path: ValuePath) -> _ElementRecord:
    """Recursive element-record validation (materialization.rs:306-500)."""
    namespace, local = _expect_expanded_name(value, path)
    namespaces: list[tuple[str | None, str]] = []
    bindings_path = path.child(ValuePathSegment.object_value("namespaces"))
    bindings_value = _optional_sequence_field(value, "namespaces")
    if bindings_value is not None:
        for index, binding in enumerate(bindings_value):
            binding_path = bindings_path.child(ValuePathSegment.sequence_element(index))
            prefix = _optional_string_field(binding, "prefix", binding_path)
            uri = _expect_string_field(binding, "uri", binding_path)
            namespaces.append((prefix, uri))
    attributes: list[_AttributeRecord] = []
    attributes_path = path.child(ValuePathSegment.object_value("attributes"))
    attributes_value = _optional_sequence_field(value, "attributes")
    if attributes_value is not None:
        for index, attribute in enumerate(attributes_value):
            attribute_path = attributes_path.child(ValuePathSegment.sequence_element(index))
            attr_namespace, attr_local = _expect_expanded_name(attribute, attribute_path)
            value_text = _expect_string_field(attribute, "value", attribute_path)
            attributes.append(
                _AttributeRecord(
                    namespace=attr_namespace, local=attr_local, value=value_text, path=attribute_path
                )
            )
    content: list[_ContentRecord] = []
    content_path = path.child(ValuePathSegment.object_value("content"))
    content_value = _optional_sequence_field(value, "content")
    if content_value is not None:
        for index, item in enumerate(content_value):
            item_path = content_path.child(ValuePathSegment.sequence_element(index))
            if item.kind.value == "Object" and _has_object_field(item, "expanded-name"):
                content.append(
                    _ContentRecord(
                        kind=_ContentKind.ELEMENT,
                        element=_ElementRecord_validate(item, item_path),
                        path=item_path,
                    )
                )
                continue
            kind = _expect_string_field(item, "kind", item_path)
            if kind == "text":
                fragments_path = item_path.child(ValuePathSegment.object_value("fragments"))
                fragments_value = _expect_object_field(item, "fragments", fragments_path)
                fragment_list: list[_FragmentRecord] = []
                if fragments_value.kind.value != "Sequence":
                    raise MaterializationFailure(
                        MaterializationFailureKind.UNREPRESENTABLE,
                        name="text-fragments",
                    )
                for fragment_index, fragment in enumerate(fragments_value.as_sequence()):
                    fragment_path = fragments_path.child(
                        ValuePathSegment.sequence_element(fragment_index)
                    )
                    fragment_kind = _expect_string_field(fragment, "kind", fragment_path)
                    if fragment_kind == "literal":
                        fragment_list.append(
                            _FragmentRecord(
                                kind=_FragmentKind.LITERAL,
                                text=_expect_string_field(fragment, "text", fragment_path),
                            )
                        )
                    elif fragment_kind == "character-reference":
                        resolved = _expect_string_field(fragment, "resolved", fragment_path)
                        if len(resolved) != 1:
                            raise MaterializationFailure(
                                MaterializationFailureKind.UNREPRESENTABLE,
                                name="character-reference",
                            )
                        fragment_list.append(
                            _FragmentRecord(
                                kind=_FragmentKind.CHARACTER_REFERENCE, resolved=resolved
                            )
                        )
                    elif fragment_kind in ("predefined-entity", "general-entity"):
                        fragment_list.append(
                            _FragmentRecord(
                                kind=_FragmentKind.PREDEFINED_ENTITY
                                if fragment_kind == "predefined-entity"
                                else _FragmentKind.GENERAL_ENTITY,
                                name=_expect_string_field(fragment, "name", fragment_path),
                                resolved=_expect_string_field(fragment, "resolved", fragment_path),
                            )
                        )
                    else:
                        raise MaterializationFailure(
                            MaterializationFailureKind.UNREPRESENTABLE,
                            name="fragment-kind",
                        )
                content.append(
                    _ContentRecord(
                        kind=_ContentKind.TEXT,
                        fragments=tuple(fragment_list),
                        path=item_path,
                    )
                )
            elif kind == "cdata":
                content.append(
                    _ContentRecord(
                        kind=_ContentKind.CDATA,
                        text=_expect_string_field(item, "text", item_path),
                        path=item_path,
                    )
                )
            elif kind == "comment":
                content.append(
                    _ContentRecord(
                        kind=_ContentKind.COMMENT,
                        text=_expect_string_field(item, "text", item_path),
                        path=item_path,
                    )
                )
            elif kind == "processing-instruction":
                content.append(
                    _ContentRecord(
                        kind=_ContentKind.PROCESSING_INSTRUCTION,
                        target=_expect_string_field(item, "target", item_path),
                        content=_optional_string_field(item, "content", item_path),
                        path=item_path,
                    )
                )
            else:
                raise MaterializationFailure(
                    MaterializationFailureKind.UNREPRESENTABLE, name="content-kind"
                )
    names: list[tuple[str | None, str]] = []
    for attribute in attributes:
        if (attribute.namespace, attribute.local) in names:
            raise MaterializationFailure(
                MaterializationFailureKind.INVALID_REQUEST,
                detail="duplicate expanded attribute in input record",
            )
        names.append((attribute.namespace, attribute.local))
    return _ElementRecord(
        namespace=namespace,
        local=local,
        namespaces=tuple(namespaces),
        attributes=tuple(attributes),
        content=tuple(content),
        path=path,
    )


