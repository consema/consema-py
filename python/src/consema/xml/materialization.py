def _encode_text(text: bytes, encoding: SourceEncoding, max_output_bytes: int) -> bytes:
    """Encodes canonical UTF-8 text into the requested output encoding
    (materialization.rs:143-172)."""
    if encoding.kind is SourceEncodingKind.UTF8:
        output = text
    elif encoding.kind in (SourceEncodingKind.UTF16LE, SourceEncodingKind.UTF16BE):
        decoded = text.decode("utf-8")
        if encoding.kind is SourceEncodingKind.UTF16LE:
            prefix = b"\xff\xfe"
            units = decoded.encode("utf-16-le")
        else:
            prefix = b"\xfe\xff"
            units = decoded.encode("utf-16-be")
        output = prefix + units
    else:
        raise MaterializationFailure(MaterializationFailureKind.UNSUPPORTED_ENCODING)
    if len(output) > max_output_bytes:
        raise MaterializationFailure(
            MaterializationFailureKind.RESOURCE_LIMIT, name="output-bytes"
        )
    return output


