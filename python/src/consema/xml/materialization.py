def _object_field(value: PortableValue, name: str) -> PortableValue | None:
    if value.kind.value != "Object":
        return None
    for key, entry in value.as_object():
        if key == name:
            return entry
    return None


def _has_object_field(value: PortableValue, name: str) -> bool:
    return _object_field(value, name) is not None


def _expect_object_field(value: PortableValue, name: str, path: ValuePath) -> PortableValue:
    field_value = _object_field(value, name)
    if field_value is None:
        raise MaterializationFailure(
            MaterializationFailureKind.INVALID_REQUEST, detail="missing record field"
        )
    return field_value


def _optional_object_field(value: PortableValue, name: str) -> PortableValue | None:
    return _object_field(value, name)


def _expect_string_field(value: PortableValue, name: str, path: ValuePath) -> str:
    field_value = _expect_object_field(value, name, path)
    if field_value.kind.value != "String":
        raise MaterializationFailure(
            MaterializationFailureKind.UNREPRESENTABLE, name="string-field"
        )
    return field_value.as_string()


def _optional_string_field(value: PortableValue, name: str, path: ValuePath) -> str | None:
    field_value = _object_field(value, name)
    if field_value is None or field_value.kind.value == "Null":
        return None
    if field_value.kind.value != "String":
        raise MaterializationFailure(
            MaterializationFailureKind.UNREPRESENTABLE, name="string-field"
        )
    return field_value.as_string()


def _optional_boolean_field(value: PortableValue, name: str, path: ValuePath) -> bool | None:
    field_value = _object_field(value, name)
    if field_value is None or field_value.kind.value == "Null":
        return None
    if field_value.kind.value != "Boolean":
        raise MaterializationFailure(
            MaterializationFailureKind.UNREPRESENTABLE, name="boolean-field"
        )
    return field_value.as_boolean()


def _optional_sequence_field(value: PortableValue, name: str):
    field_value = _object_field(value, name)
    if field_value is None:
        return None
    if field_value.kind.value != "Sequence":
        raise MaterializationFailure(
            MaterializationFailureKind.UNREPRESENTABLE, name="sequence-field"
        )
    return field_value.as_sequence()


def _expect_expanded_name(value: PortableValue, path: ValuePath) -> tuple[str | None, str]:
    """Reads an expanded-name object (materialization.rs:1356-1366)."""
    name_path = path.child(ValuePathSegment.object_value("expanded-name"))
    name = _expect_object_field(value, "expanded-name", name_path)
    namespace = _optional_string_field(name, "namespace", name_path)
    local = _expect_string_field(name, "local", name_path)
    return namespace, local


