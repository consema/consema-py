def materialize(value: PortableValue, request: MaterializationRequest) -> MaterializationResult:
    """Materializes one ``xml.element-tree@1`` record into a new canonical
    ``xml.1.0-safe@1`` document (materialization.rs:36-50)."""
    try:
        complete = _materialize_complete(value, request)
        return complete
    except MaterializationFailure as failure:
        return FailedMaterializationAttempt(
            failure=failure,
            report=MaterializationReport(),
            analyzed_input_paths=(),
        )


def _materialize_complete(
    value: PortableValue, request: MaterializationRequest
) -> CompleteMaterialization:
    _validate_request(request)
    input_record = _Record.validate(value)
    writer = _Writer(request.limits)
    writer.emit_document(input_record, request)
    text = writer.output
    bytes_output = _encode_text(text, request.encoding, request.limits.max_output_bytes)
    document = parse(
        bytes_output,
        XmlProfile.SAFE_V1,
        XmlEncodingSelection.profile_default(),
        _parse_limits(request.limits),
    )
    if document.status is not FormationStatus.COMPLETE:
        raise MaterializationFailure(MaterializationFailureKind.FORMATION_FAILED)
    provenance = _verify_closure(input_record, document, writer.items, request.limits)
    return CompleteMaterialization(
        document=document,
        fidelity=MaterializationFidelity.EXACT,
        report=MaterializationReport(),
        provenance=provenance,
    )


def _validate_request(request: MaterializationRequest) -> None:
    """materialization.rs:90-107."""
    if (request.target_profile.id, request.target_profile.version) != ("xml.1.0-safe", 1):
        raise MaterializationFailure(MaterializationFailureKind.UNSUPPORTED_PROFILE)
    if (request.style.id, request.style.version) != ("xml.safe-canonical-document", 1):
        raise MaterializationFailure(MaterializationFailureKind.UNSUPPORTED_STYLE)
    if request.encoding.kind not in (
        SourceEncodingKind.UTF8,
        SourceEncodingKind.UTF16LE,
        SourceEncodingKind.UTF16BE,
    ):
        raise MaterializationFailure(MaterializationFailureKind.UNSUPPORTED_ENCODING)
    if request.newline not in (NewlinePolicy.LF, NewlinePolicy.CRLF):
        raise MaterializationFailure(MaterializationFailureKind.UNSUPPORTED_NEWLINE)


