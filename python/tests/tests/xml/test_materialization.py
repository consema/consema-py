def test_request_validation_rejects_foreign_contracts():
    """The canonical style accepts exactly the xml.1.0-safe@1 profile, the
    xml.safe-canonical-document@1 style, UTF-8/UTF-16 encodings, and
    LF/CRLF newlines (materialization.rs:90-107)."""
    record = _json_value({
        "record": "xml.element-tree@1",
        "root": {"expanded-name": {"namespace": None, "local": "root"}},
    })
    wrong_profile = MaterializationRequest.new(
        ProfileId.new("toml.1.0", 1),
        MaterializationStyleId.new("xml.safe-canonical-document", 1),
    )
    result = materialize(record, wrong_profile)
    assert result.failure.kind is MaterializationFailureKind.UNSUPPORTED_PROFILE
    wrong_style = MaterializationRequest.new(
        ProfileId.new("xml.1.0-safe", 1),
        MaterializationStyleId.new("toml.canonical-document", 1),
    )
    result = materialize(record, wrong_style)
    assert result.failure.kind is MaterializationFailureKind.UNSUPPORTED_STYLE


def test_utf16_output_carries_bom():
    """UTF-16 output always carries its corresponding BOM and a matching
    declaration (RFC 0012 §10, lines 364-366; materialization.rs:651-685).
    The declaration is emitted only when the record declares one; a
    UTF-16 output then forces the ``UTF-16`` spelling."""
    record = _json_value({
        "record": "xml.element-tree@1",
        "declaration": {"version": "1.0"},
        "root": {"expanded-name": {"namespace": None, "local": "root"}},
    })
    request = _request().with_encoding(SourceEncoding.utf16le())
    result = materialize(record, request)
    render = result.document.render()
    assert render.startswith(b"\xff\xfe")
    assert result.document.source().encoding_facts().selected == SourceEncoding.utf16le()
    declared = result.document.declaration()
    assert declared is not None
    assert declared.version == "1.0"
    assert declared.encoding[1] == "UTF-16"
    # A record without a declaration materializes without one (the vector
    # canonical-round-trip render has no declaration either).
    record = _json_value({
        "record": "xml.element-tree@1",
        "root": {"expanded-name": {"namespace": None, "local": "root"}},
    })
    result = materialize(record, _request())
    assert result.document.declaration() is None


def test_closure_verifies_reparsed_semantics():
    """Materialization reparses the exact generated bytes and compares the
    reparsed native tree to the promised input semantics
    (materialization.rs:912-1210); provenance covers every emitted value
    (RFC 0004 §8)."""
    doc = form_document(
        {"input": {"profile": "xml.1.0-safe@1", "source": '<root a="1"><child>t</child></root>'}}
    )
    projection = project_document(doc, ProjectionRequest.element_tree())
    result = materialize(projection.value, _request())
    assert result.document.status.value == "Complete"
    assert len(result.provenance.entries) > 0
    for entry in result.provenance.entries:
        for origin in entry.outputs:
            assert origin.snapshot == result.document.snapshot_identity()
