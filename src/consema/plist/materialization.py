class PlistMaterializationFailureKind(enum.Enum):
    """Stable plist materialization failure categories (materialization.rs:
    78-95 plus the shared core kinds)."""

    FRACTIONAL_DATE = "fractional-date"
    UNREPRESENTABLE = "unrepresentable"
    RESOURCE_LIMIT = "resource-limit"
    INVALID_REQUEST = "invalid-request"
    UNSUPPORTED_PROFILE = "unsupported-profile"
    UNSUPPORTED_STYLE = "unsupported-style"
    UNSUPPORTED_ENCODING = "unsupported-encoding"
    UNSUPPORTED_NEWLINE = "unsupported-newline"
    FORMATION_FAILED = "formation-failed"


class _PlistCodedFailure(MaterializationFailure):
    """Shared-shaped failure carrying the plist-owned ``plist.materialization.*@1``
    spellings for the plist materialization facts (RFC 0013 §12).

    Mirrors go/plist/materialization.go Code() (lines 125-140): a Date-kind
    Unrepresentable maps to ``plist.materialization.fractional-date@1``,
    every other plist Unrepresentable to ``plist.materialization.unrepresentable@1``,
    and ResourceLimit to ``plist.materialization.resource-limit@1``; the
    shared request/formation failures keep the shared
    ``core.materialization.*@1`` codes.
    """

    @property
    def code(self) -> str:
        if self.kind is MaterializationFailureKind.UNREPRESENTABLE:
            if self.name == "date":
                return "plist.materialization.fractional-date@1"
            return "plist.materialization.unrepresentable@1"
        if self.kind is MaterializationFailureKind.RESOURCE_LIMIT:
            return "plist.materialization.resource-limit@1"
        return super().code


class PlistMaterializationFailure(Exception):
    """Stable plist materialization failure.

    Code mapping authority: materialization.rs:78-95 and
    crates/consema-conformance/src/plist_v1.rs:1800-1816 — a Date kind maps
    to ``plist.materialization.fractional-date@1``, other plist facts to
    ``plist.materialization.unrepresentable@1`` / ``resource-limit@1``, and
    the shared request/formation failures to the ``core.materialization.*@1``
    codes.
    """

    def __init__(
        self,
        kind: PlistMaterializationFailureKind,
        *,
        name: str | None = None,
        detail: str | None = None,
    ) -> None:
        super().__init__(kind.value)
        self.kind = kind
        self.name = name
        self.detail = detail

    @property
    def code(self) -> str:
        if self.kind is PlistMaterializationFailureKind.FRACTIONAL_DATE:
            return _FRACTIONAL_DATE_CODE
        if self.kind is PlistMaterializationFailureKind.UNREPRESENTABLE:
            return "plist.materialization.unrepresentable@1"
        if self.kind is PlistMaterializationFailureKind.RESOURCE_LIMIT:
            return "plist.materialization.resource-limit@1"
        return {
            PlistMaterializationFailureKind.INVALID_REQUEST: "core.materialization.invalid-request@1",
            PlistMaterializationFailureKind.UNSUPPORTED_PROFILE: "core.materialization.unsupported-profile@1",
            PlistMaterializationFailureKind.UNSUPPORTED_STYLE: "core.materialization.unsupported-style@1",
            PlistMaterializationFailureKind.UNSUPPORTED_ENCODING: "core.materialization.unsupported-encoding@1",
            PlistMaterializationFailureKind.UNSUPPORTED_NEWLINE: "core.materialization.unsupported-newline@1",
            PlistMaterializationFailureKind.FORMATION_FAILED: "core.materialization.formation-failed@1",
        }[self.kind]


