def _write_indent(out: list[str], depth: int) -> None:
    for _ in range(depth):
        out.append("    ")


def _escape_xml_text(text: str) -> str:
    """Escapes XML text content (RFC 0013 §4.9, §10.1): ``&``, ``<``, ``>``,
    and a literal CR (materialization.rs:1218-1234)."""
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\r", "&#13;")
    )


def _render_real(real: PlistReal) -> str:
    """Deterministic shortest-round-trip decimal spelling of one real
    (RFC 0013 §4.6, §10.1; materialization.rs:1235-1253)."""
    value = real.as_f64()
    if value != value:
        return "nan"
    if abs(value) == float("inf"):
        return "-inf" if value < 0 else "inf"
    return repr(value)


def _civil_from_days(days: int) -> tuple[int, int, int]:
    z = days + 719_468
    era = (z if z >= 0 else z - 146_096) // 146_097
    day_of_era = z - era * 146_097
    year_of_era = (
        day_of_era - day_of_era // 1_460 + day_of_era // 36_524 - day_of_era // 146_096
    ) // 365
    year = year_of_era + era * 400
    day_of_year = day_of_era - (365 * year_of_era + year_of_era // 4 - year_of_era // 100)
    month_prime = (5 * day_of_year + 2) // 153
    day = day_of_year - (153 * month_prime + 2) // 5 + 1
    month = month_prime + (3 if month_prime < 10 else -9)
    year = year + 1 if month <= 2 else year
    return (year, month, day)


def _whole_second_date(seconds: float) -> tuple[int, int, int, int, int, int] | None:
    """Decomposes exact plist-epoch seconds into XML calendar fields
    (materialization.rs:1292-1336)."""
    if seconds != int(seconds):
        return None
    unix = seconds + PLIST_EPOCH_OFFSET_UNIX
    if abs(unix) >= _EXACT_UNIX_SECONDS_BOUND:
        return None
    unix_int = int(unix)
    days = unix_int // 86_400
    seconds_of_day = unix_int % 86_400
    year, month, day = _civil_from_days(days)
    if abs(year) > 0xFFFFFFFF:
        return None
    hour = seconds_of_day // 3_600
    minute = (seconds_of_day % 3_600) // 60
    second = seconds_of_day % 60
    return (year, month, day, hour, minute, second)


def _render_date(year: int, month: int, day: int, hour: int, minute: int, second: int) -> str:
    sign = "-" if year < 0 else ""
    return f"{sign}{abs(year):04}-{month:02}-{day:02}T{hour:02}:{minute:02}:{second:02}Z"


def _encode_base64_wrapped(bytes_: bytes, depth: int) -> str:
    """Standard-alphabet base64 wrapped at ``76 - 8 * depth`` with the
    indentation counted against the budget (RFC 0013 §4.8, §10.1;
    materialization.rs:1338-1369)."""
    import base64

    budget = max(76 - 8 * depth, 1)
    encoded = base64.b64encode(bytes_).decode("ascii")
    out: list[str] = []
    line = 0
    for character in encoded:
        if line + 1 > budget and line > 0:
            out.append("\n")
            _write_indent(out, depth)
            line = 0
        out.append(character)
        line += 1
    return "".join(out)


def _serialize_xml(
    root: _ValueNode,
    truncate: str | None,
    limits: MaterializationLimits,
    report: list,
) -> tuple[bytes, list]:
    out: list[str] = []
    out.append('<?xml version="1.0" encoding="UTF-8"?>\n')
    out.append(
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
        '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
    )
    out.append('<plist version="1.0">\n')
    items: list = []
    rank = 0
    _emit_value_xml(out, root, 1, items, rank, truncate, limits, report)
    out.append("</plist>\n")
    text = "".join(out)
    if len(text.encode("utf-8")) > limits.max_output_bytes:
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.RESOURCE_LIMIT, name="output-bytes"
        )
    return text.encode("utf-8"), items


def _emit_value_xml(
    out: list[str],
    node: _ValueNode,
    depth: int,
    items: list,
    rank: int,
    truncate: str | None,
    limits: MaterializationLimits,
    report: list,
) -> int:
    """Emits one value element at the given depth; the node's target ordinal
    is its post-order rank (materialization.rs:1123-1209)."""
    kind = node.kind
    if kind is _ValueKind.DICT:
        _write_indent(out, depth)
        if not node.entries:
            out.append("<dict></dict>\n")
        else:
            out.append("<dict>\n")
            for key, child in node.entries:
                _write_indent(out, depth + 1)
                out.append("<key>")
                out.append(_escape_xml_text(key.to_unicode()))
                out.append("</key>\n")
                rank = _emit_value_xml(out, child, depth + 1, items, rank, truncate, limits, report)
            _write_indent(out, depth)
            out.append("</dict>\n")
    elif kind is _ValueKind.ARRAY:
        _write_indent(out, depth)
        if not node.elements:
            out.append("<array></array>\n")
        else:
            out.append("<array>\n")
            for element in node.elements:
                rank = _emit_value_xml(out, element, depth + 1, items, rank, truncate, limits, report)
            _write_indent(out, depth)
            out.append("</array>\n")
    elif kind is _ValueKind.STRING:
        _write_indent(out, depth)
        out.append("<string>")
        out.append(_escape_xml_text(node.string.to_unicode()))
        out.append("</string>\n")
    elif kind is _ValueKind.INTEGER:
        _write_indent(out, depth)
        out.append(f"<integer>{node.integer}</integer>\n")
    elif kind is _ValueKind.REAL:
        _write_indent(out, depth)
        out.append(f"<real>{_render_real(node.real)}</real>\n")
    elif kind is _ValueKind.BOOLEAN:
        _write_indent(out, depth)
        out.append("<true/>\n" if node.boolean else "<false/>\n")
    elif kind is _ValueKind.DATE:
        seconds = node.date_seconds
        fields = _whole_second_date(seconds)
        if fields is None:
            if truncate == _TRUNCATE_POLICY:
                fields = _whole_second_date(float(int(seconds)))
            if fields is None:
                raise PlistMaterializationFailure(
                    PlistMaterializationFailureKind.FRACTIONAL_DATE,
                    detail=f"seconds={seconds!r}",
                )
            # One report event per truncated date, with the input value
            # path and the original seconds (RFC 0013 §10.1, hard gate 3);
            # the promised semantics become the truncated seconds so the
            # reparse closure stays exact.
            report.append(
                (
                    _FRACTIONAL_DATE_CODE,
                    node.path,
                    seconds,
                )
            )
            if len(report) > limits.max_report_entries:
                raise PlistMaterializationFailure(
                    PlistMaterializationFailureKind.RESOURCE_LIMIT,
                    name="report-entries",
                )
            node.date_seconds = float(int(seconds))
        _write_indent(out, depth)
        out.append(f"<date>{_render_date(*fields)}</date>\n")
    elif kind is _ValueKind.DATA:
        _write_indent(out, depth)
        out.append("<data>")
        out.append(_encode_base64_wrapped(node.data, depth))
        out.append("</data>\n")
    else:  # UID is binary-only
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.UNREPRESENTABLE,
            detail="uid-in-xml",
        )
    items.append((node.path, rank))
    rank += 1
    if len("".join(out).encode("utf-8")) > limits.max_output_bytes:
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.RESOURCE_LIMIT, name="output-bytes"
        )
    return rank


