"""Canonical ``plist.xml-canonical@1`` / ``plist.binary-canonical@1``
materialization (RFC 0013 §10).

Authority (Rust arbitration for exact bytes and semantics):

- Record contract and request contract: crates/consema-plist/src/
  materialization.rs:1-115 — the input is the exact ``plist.value-tree@1``
  record (``{ "record": "plist.value-tree@1", "root": <value>,
  "truncate_policy": "TruncateWithReport" | absent }``); dict associations
  are ordered and duplicate keys are preserved; ``plist.xml-canonical@1``
  requires UTF-8 + Lf, ``plist.binary-canonical@1`` requires Binary + None.
- XML writer: materialization.rs:1105-1209 (Apple header spelling,
  four-space indentation, LF line endings, a trailing newline; the root
  value element at depth 1; ``<key>`` lines before every value; data
  base64 wrapped at ``76 - 8 * depth`` against the indented budget
  (encode_base64_wrapped 1338-1369); whole-second dates with the explicit
  TruncateWithReport policy (RFC 0013 §10.1); escape_xml_text 1218-1234).
- Binary writer: materialization.rs:1414-1520 (document-ordered object
  table: the root is object 0, every dictionary is followed by its key
  objects and then its values; minimal integer widths with negatives
  always 8 bytes; Float32 width facts preserved; identical deduplicable
  scalars share one object at first occurrence; minimal UID widths; the
  offset/ref sizes are the minimal widths satisfying the trailer
  sufficiency checks; ``sortVersion = 0x00``; write_sized 1549-1559).
- Closure: materialization.rs:60-66, 489-535 — every style validates the
  complete input, encodes, reparses the exact generated bytes under the
  promised Profile, and compares the reparsed native model to the promised
  input semantics; failure returns no target Document, partial bytes, or
  partial provenance (RFC 0013 §10.3).
- Failure mapping: materialization.rs:78-95 and go/plist/materialization.go
  Code() — a Date kind marks a value-tree date leaf the XML whole-second
  calendar cannot express (``plist.materialization.fractional-date@1``);
  the returned failure carries the plist-owned ``plist.materialization.*@1``
  spellings for the plist facts (fractional-date, unrepresentable,
  resource-limit; RFC 0013 §12) and the shared ``core.materialization.*@1``
  codes for the request/formation failures.

This module defines a plist-owned ``PlistMaterializationFailure`` that
carries the stable ``plist.materialization.*@1`` code for the fractional-
date case and delegates the shared codes to consema.document's
``MaterializationFailure``; ``materialize`` surfaces every plist failure
through ``_PlistCodedFailure`` so the plist spellings reach the caller
directly.
"""

