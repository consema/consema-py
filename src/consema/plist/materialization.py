def _write_sized(out: bytearray, marker: int, count: int) -> None:
    """Writes one sized marker: counts below 0x0F fit the low nibble, while
    the nibble 0x0F itself is the extended-size sentinel (RFC 0013 §5.4;
    materialization.rs:1549-1559)."""
    if count < 0x0F:
        out.append(marker | count)
        return
    out.append(marker | 0x0F)
    width = _unsigned_width(count)
    out.append(0x10 | {1: 0, 2: 1, 4: 2, 8: 3}[width])
    out.extend(count.to_bytes(width, "big"))


def _write_string_object(out: bytearray, string: PlistString) -> None:
    """Writes one string object: the ASCII marker when every code unit is
    below 0x80, else the UTF-16BE marker (RFC 0013 §5.6;
    materialization.rs:1524-1541)."""
    units = string.code_units
    if all(unit < 0x80 for unit in units):
        _write_sized(out, 0x50, len(units))
        for unit in units:
            out.append(unit)
    else:
        _write_sized(out, 0x60, len(units))
        for unit in units:
            out.extend(unit.to_bytes(2, "big"))


def _write_be(out: bytearray, value: int, width: int) -> None:
    out.extend(value.to_bytes(width, "big"))


def _ref_size_for(max_index: int) -> int:
    size = 1
    capacity = 256
    while max_index >= capacity and size < 8:
        size += 1
        capacity *= 256
    return size


def _unsigned_width(value: int) -> int:
    if value <= 0xFF:
        return 1
    if value <= 0xFFFF:
        return 2
    if value <= 0xFFFF_FFFF:
        return 4
    return 8


def _integer_width(value: int) -> int:
    if value >= 0:
        return _unsigned_width(value)
    return 8


def _uid_width(value: int) -> int:
    if value <= 0xFF:
        return 1
    if value <= 0xFFFF:
        return 2
    if value <= 0xFF_FFFF:
        return 3
    return 4


class _ScalarKey:
    """Deduplication key of one scalar node (materialization.rs:1011-1081)."""

    __slots__ = ("kind", "payload")

    def __init__(self, kind: str, payload: object) -> None:
        self.kind = kind
        self.payload = payload

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, _ScalarKey):
            return NotImplemented
        return self.kind == other.kind and self.payload == other.payload

    def __hash__(self) -> int:
        return hash((self.kind, self.payload))


class _PlannedObject:
    __slots__ = ("kind", "keys", "values", "elements", "scalar")

    def __init__(self, kind: str) -> None:
        self.kind = kind  # "dict" | "array" | "scalar"
        self.keys: list[int] = []
        self.values: list[int] = []
        self.elements: list[int] = []
        self.scalar: _ScalarKey | None = None


def _plan_binary(root: _ValueNode, limits: MaterializationLimits) -> tuple[list[_PlannedObject], list, dict]:
    """Plans the document-ordered object table with scalar deduplication at
    first occurrence (materialization.rs:1011-1103)."""
    objects: list[_PlannedObject] = []
    items: list = []
    cache: dict[_ScalarKey, int] = {}

    def plan_node(node: _ValueNode) -> int:
        kind = node.kind
        if kind is _ValueKind.DICT:
            index = len(objects)
            objects.append(_PlannedObject("dict"))
            items.append((node.path, index))
            key_refs: list[int] = []
            for key, _ in node.entries:
                scalar = _ScalarKey("string", key.code_units)
                key_index = cache.get(scalar)
                if key_index is None:
                    key_index = len(objects)
                    objects.append(_PlannedObject("scalar"))
                    objects[-1].scalar = scalar
                    cache[scalar] = key_index
                key_refs.append(key_index)
            value_refs = [plan_node(entry_value) for _, entry_value in node.entries]
            objects[index].keys = key_refs
            objects[index].values = value_refs
            return index
        if kind is _ValueKind.ARRAY:
            index = len(objects)
            objects.append(_PlannedObject("array"))
            items.append((node.path, index))
            objects[index].elements = [plan_node(element) for element in node.elements]
            return index
        scalar = _node_scalar(node)
        if scalar is not None:
            cached = cache.get(scalar)
            if cached is not None:
                items.append((node.path, cached))
                return cached
            index = len(objects)
            objects.append(_PlannedObject("scalar"))
            objects[-1].scalar = scalar
            cache[scalar] = index
            items.append((node.path, index))
            return index
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.UNREPRESENTABLE,
            detail=node.kind.value,
        )

    plan_node(root)
    return objects, items, cache


def _node_scalar(node: _ValueNode) -> _ScalarKey | None:
    kind = node.kind
    if kind is _ValueKind.STRING:
        return _ScalarKey("string", node.string.code_units)
    if kind is _ValueKind.INTEGER:
        return _ScalarKey("integer", node.integer)
    if kind is _ValueKind.REAL:
        return _ScalarKey("real", (node.real.width.value, node.real.bits))
    if kind is _ValueKind.BOOLEAN:
        return _ScalarKey("boolean", node.boolean)
    if kind is _ValueKind.DATE:
        return _ScalarKey("date", _bits_of(node.date_seconds))
    if kind is _ValueKind.DATA:
        return _ScalarKey("data", node.data)
    if kind is _ValueKind.UID:
        return _ScalarKey("uid", node.uid)
    return None


def _write_planned_object(
    out: bytearray, object_: _PlannedObject, ref_size: int
) -> None:
    """Writes one planned object: marker, size, payload, and references
    (RFC 0013 §5; materialization.rs:1456-1520)."""
    if object_.kind == "dict":
        count = len(object_.keys)
        _write_sized(out, 0xD0, count)
        for key in object_.keys:
            _write_be(out, key, ref_size)
        for value in object_.values:
            _write_be(out, value, ref_size)
    elif object_.kind == "array":
        count = len(object_.elements)
        _write_sized(out, 0xA0, count)
        for element in object_.elements:
            _write_be(out, element, ref_size)
    else:
        scalar = object_.scalar
        assert scalar is not None
        if scalar.kind == "string":
            _write_string_object(out, PlistString(scalar.payload))
        elif scalar.kind == "integer":
            value = scalar.payload
            width = _integer_width(value)
            out.append(0x10 | {1: 0, 2: 1, 4: 2, 8: 3}[width])
            _write_be(out, value & 0xFFFFFFFFFFFFFFFF, width)
        elif scalar.kind == "real":
            width_name, bits = scalar.payload
            if width_name == "Float64":
                out.append(0x23)
                _write_be(out, bits, 8)
            else:
                out.append(0x22)
                _write_be(out, bits, 4)
        elif scalar.kind == "boolean":
            out.append(0x09 if scalar.payload else 0x08)
        elif scalar.kind == "date":
            out.append(0x33)
            _write_be(out, scalar.payload, 8)
        elif scalar.kind == "data":
            _write_sized(out, 0x40, len(scalar.payload))
            out.extend(scalar.payload)
        elif scalar.kind == "uid":
            value = scalar.payload
            width = _uid_width(value)
            out.append(0x80 | (width - 1))
            _write_be(out, value, width)


def _serialize_binary(
    root: _ValueNode, limits: MaterializationLimits
) -> tuple[bytes, list]:
    """Serializes one record as a ``plist.binary@1`` source
    (materialization.rs:1414-1452)."""
    objects, items, _ = _plan_binary(root, limits)
    num_objects = len(objects)
    ref_size = _ref_size_for(num_objects)
    out = bytearray(b"bplist00")
    offsets: list[int] = []
    for object_ in objects:
        offsets.append(len(out))
        _write_planned_object(out, object_, ref_size)
        if len(out) > limits.max_output_bytes:
            raise PlistMaterializationFailure(
                PlistMaterializationFailureKind.RESOURCE_LIMIT, name="output-bytes"
            )
    offset_table_offset = len(out)
    offset_int_size = _ref_size_for(offset_table_offset)
    for offset in offsets:
        _write_be(out, offset, offset_int_size)
    out.extend(b"\x00\x00\x00\x00\x00")
    out.append(0)  # sortVersion
    out.append(offset_int_size)
    out.append(ref_size)
    out.extend(num_objects.to_bytes(8, "big"))
    out.extend((0).to_bytes(8, "big"))  # topObject: the root is object 0
    out.extend(offset_table_offset.to_bytes(8, "big"))
    return bytes(out), items


