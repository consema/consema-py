def requested_profile(request: MaterializationRequest) -> PlistProfile:
    """Resolves the target profile (materialization.rs:77-89)."""
    if request.target_profile.id == "plist.xml" and request.target_profile.version == 1:
        return PlistProfile.XML_V1
    if request.target_profile.id == "plist.binary" and request.target_profile.version == 1:
        return PlistProfile.BINARY_V1
    raise PlistMaterializationFailure(PlistMaterializationFailureKind.UNSUPPORTED_PROFILE)


def validate_request(request: MaterializationRequest, profile: PlistProfile) -> _Style:
    """Style, newline, and encoding closure (materialization.rs:91-127;
    RFC 0013 §10.1-§10.2)."""
    from consema.document.source import SourceEncoding, SourceEncodingKind

    if (
        profile is PlistProfile.XML_V1
        and request.style.id == _STYLE_XML
        and request.style.version == 1
    ):
        style = _Style.XML
        if request.encoding != SourceEncoding.utf8():
            raise PlistMaterializationFailure(PlistMaterializationFailureKind.UNSUPPORTED_ENCODING)
        if request.newline is not NewlinePolicy.LF:
            raise PlistMaterializationFailure(PlistMaterializationFailureKind.UNSUPPORTED_NEWLINE)
        return style
    if (
        profile is PlistProfile.BINARY_V1
        and request.style.id == _STYLE_BINARY
        and request.style.version == 1
    ):
        style = _Style.BINARY
        if request.encoding.kind is not SourceEncodingKind.BINARY:
            raise PlistMaterializationFailure(PlistMaterializationFailureKind.UNSUPPORTED_ENCODING)
        if request.newline is not NewlinePolicy.NONE:
            raise PlistMaterializationFailure(PlistMaterializationFailureKind.UNSUPPORTED_NEWLINE)
        return style
    raise PlistMaterializationFailure(PlistMaterializationFailureKind.UNSUPPORTED_STYLE)


def materialize(
    value: PortableValue, request: MaterializationRequest
) -> MaterializationResult:
    """Materializes one ``plist.value-tree@1`` record into a new canonical
    plist document (RFC 0013 §10; materialization.rs:178-260).

    The requested style selects the target profile and representation:
    ``plist.xml-canonical@1`` produces a ``plist.xml@1`` Document and
    ``plist.binary-canonical@1`` a ``plist.binary@1`` Document. The
    generated bytes are reparsed under the promised Profile and the reparsed
    native model is compared to the promised input semantics; failure
    returns no target Document, no partial bytes, and no partial
    provenance."""
    analyzed: list = []
    try:
        complete = _materialize_complete(value, request, analyzed)
    except PlistMaterializationFailure as failure:
        # The date-kind name distinguishes the fractional-date spelling
        # (go/plist/materialization.go:125-140); the returned failure carries
        # the plist-owned ``plist.materialization.*@1`` codes directly.
        name = (
            "date"
            if failure.kind is PlistMaterializationFailureKind.FRACTIONAL_DATE
            else failure.name
        )
        return FailedMaterializationAttempt(
            failure=_PlistCodedFailure(
                _materialization_kind(failure), name=name, detail=failure.detail
            ),
            report=MaterializationReport(),
            analyzed_input_paths=tuple(analyzed),
        )
    except MaterializationFailure as failure:
        return FailedMaterializationAttempt(
            failure=failure,
            report=MaterializationReport(),
            analyzed_input_paths=tuple(analyzed),
        )
    return complete


def _materialization_kind(failure: PlistMaterializationFailure) -> MaterializationFailureKind:
    return {
        PlistMaterializationFailureKind.FRACTIONAL_DATE: MaterializationFailureKind.UNREPRESENTABLE,
        PlistMaterializationFailureKind.UNREPRESENTABLE: MaterializationFailureKind.UNREPRESENTABLE,
        PlistMaterializationFailureKind.RESOURCE_LIMIT: MaterializationFailureKind.RESOURCE_LIMIT,
        PlistMaterializationFailureKind.INVALID_REQUEST: MaterializationFailureKind.INVALID_REQUEST,
        PlistMaterializationFailureKind.UNSUPPORTED_PROFILE: MaterializationFailureKind.UNSUPPORTED_PROFILE,
        PlistMaterializationFailureKind.UNSUPPORTED_STYLE: MaterializationFailureKind.UNSUPPORTED_STYLE,
        PlistMaterializationFailureKind.UNSUPPORTED_ENCODING: MaterializationFailureKind.UNSUPPORTED_ENCODING,
        PlistMaterializationFailureKind.UNSUPPORTED_NEWLINE: MaterializationFailureKind.UNSUPPORTED_NEWLINE,
        PlistMaterializationFailureKind.FORMATION_FAILED: MaterializationFailureKind.FORMATION_FAILED,
    }[failure.kind]


def _materialize_complete(
    value: PortableValue,
    request: MaterializationRequest,
    analyzed: list,
) -> CompleteMaterialization:
    profile = requested_profile(request)
    style = validate_request(request, profile)
    root = parse_record(value, analyzed)
    limits = request.limits
    truncate = _record_truncate_policy(value)
    report_events: list = []
    if style is _Style.XML:
        bytes_, items = _serialize_xml(root, truncate, limits, report_events)
        selection = PlistEncodingSelection.profile_default()
        formed = parse_xml(bytes_, selection, _reparse_limits(limits, "utf8"))
        document = PlistDocument(
            authority=formed.authority,
            source=formed.source,
            profile=profile,
            _representation=PlistRepresentation.XML,
            _formation_status=formed.status,
            diagnostics=formed.diagnostics,
            native=formed.document,
            formed_xml=formed,
            root_node=formed.root_node,
        )
    else:
        bytes_, items = _serialize_binary(root, limits)
        from consema.plist.parser_binary import parse_binary

        formed = parse_binary(bytes_, PlistEncodingSelection.profile_default(), _reparse_limits(limits, "binary"))
        document = PlistDocument(
            authority=formed.authority,
            source=formed.source,
            profile=profile,
            _representation=PlistRepresentation.BINARY,
            _formation_status=formed.status,
            diagnostics=formed.diagnostics,
            native=formed.document,
            formed_binary=formed,
            root_node=formed.root_node,
        )
    if document.formation_status() is not FormationStatus.COMPLETE:
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.FORMATION_FAILED,
            detail="reparse recovered",
        )
    promised = _promised_native(root, limits)
    _verify_closure(promised, document)
    provenance = _build_provenance(items, document, style, limits)
    fidelity = (
        MaterializationFidelity.TRANSFORMED
        if report_events
        else MaterializationFidelity.EXACT
    )
    report = MaterializationReport.new(report_events, limits)
    return CompleteMaterialization(
        document=document,
        fidelity=fidelity,
        report=report,
        provenance=provenance,
    )


def _record_truncate_policy(value: PortableValue) -> str | None:
    """The record's explicit truncation policy, when present."""
    fields = dict(value.as_object())
    policy = fields.get("truncate_policy")
    if policy is None:
        return None
    if policy.kind is not Kind.STRING or policy.as_string() != _TRUNCATE_POLICY:
        return None
    return _TRUNCATE_POLICY
