def _reparse_limits(limits: MaterializationLimits, encoding_kind: str) -> PlistParseLimits:
    """Parse limits derived from the request so a bounded input cannot fail
    its own closure (materialization.rs:137-160)."""
    from consema.document.limits import ParseLimits

    return PlistParseLimits(
        common=ParseLimits(
            max_source_bytes=limits.max_output_bytes,
            max_nesting_depth=limits.max_depth,
            max_token_count=limits.max_output_bytes,
            max_node_count=limits.max_output_bytes,
            max_diagnostics=limits.max_report_entries,
        ),
        max_decoded_utf8_bytes=limits.max_output_bytes * 3,
        max_decoded_scalars=limits.max_output_bytes,
        max_object_count=limits.max_input_nodes,
        max_container_depth=limits.max_depth,
        max_dict_entries=limits.max_input_nodes,
        max_array_elements=limits.max_input_nodes,
        max_duplicate_key_group_members=limits.max_input_nodes,
        max_string_code_units=limits.max_output_bytes,
        max_data_bytes=limits.max_output_bytes,
        max_uid_count=limits.max_input_nodes,
        max_extended_size_integers=limits.max_input_nodes,
        max_extended_size_value=limits.max_output_bytes,
        max_offset_int_size=8,
        max_object_ref_size=8,
        max_offset_table_bytes=limits.max_output_bytes,
        max_syntax_pieces=limits.max_output_bytes,
        max_binary_facts=limits.max_output_bytes,
        max_conversion_nodes=limits.max_input_nodes,
        max_report_events=limits.max_report_entries,
        max_recovery_regions=limits.max_report_entries,
    )


def _promised_native(root: _ValueNode, limits: MaterializationLimits) -> NativeDocument:
    """Builds the promised native model of one parsed record (the input
    semantics the closure compares against)."""
    builder = PlistDocumentBuilder()

    def build(node: _ValueNode, depth: int) -> PlistValueRef:
        if depth > limits.max_depth:
            raise PlistMaterializationFailure(
                PlistMaterializationFailureKind.RESOURCE_LIMIT, name="depth"
            )
        kind = node.kind
        if kind is _ValueKind.DICT:
            refs = [(PlistKey(key), build(child, depth + 1)) for key, child in node.entries]
            value = PlistValue.dict(
                PlistDict(tuple(PlistDictEntry(key, ref) for key, ref in refs))
            )
            return builder.add(value)
        if kind is _ValueKind.ARRAY:
            value = PlistValue.array(
                PlistArray(tuple(build(element, depth + 1) for element in node.elements))
            )
            return builder.add(value)
        if kind is _ValueKind.STRING:
            return builder.add(PlistValue.string(node.string))
        if kind is _ValueKind.INTEGER:
            return builder.add(PlistValue.integer(PlistInteger(node.integer)))
        if kind is _ValueKind.REAL:
            return builder.add(PlistValue.real(node.real))
        if kind is _ValueKind.BOOLEAN:
            return builder.add(PlistValue.boolean(PlistBoolean(node.boolean)))
        if kind is _ValueKind.DATE:
            return builder.add(PlistValue.date(PlistDate.from_seconds(node.date_seconds)))
        if kind is _ValueKind.DATA:
            return builder.add(PlistValue.data(PlistData(node.data)))
        if kind is _ValueKind.UID:
            return builder.add(PlistValue.uid(PlistUid(node.uid)))
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.UNREPRESENTABLE,
            detail=node.kind.value,
        )

    root_ref = build(root, 0)
    try:
        return builder.build(root_ref)
    except Exception:
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.UNREPRESENTABLE,
            detail="arena",
        ) from None


def _verify_closure(
    promised: NativeDocument, document: PlistDocument
) -> None:
    """Reparse closure: the reparsed native model must equal the promised
    input semantics (RFC 0013 §10.3; materialization.rs:489-535)."""
    actual = document.document()
    if actual is None or actual != promised:
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.FORMATION_FAILED,
            detail="closure",
        )


def _build_provenance(
    items: list, document: PlistDocument, style: _Style, limits: MaterializationLimits
) -> MaterializationProvenanceMap:
    """Pairs every recorded input item with its exact output origin
    (materialization.rs:1619-1720)."""
    from consema.document.materialization import MaterializationInputLocation as _Loc
    from consema.plist.projection import ValuePath, ValuePathSegment, ValuePathSegmentKind

    entries: list[MaterializationProvenanceEntry] = []
    authority = document.authority
    identity = document.snapshot_identity()
    for path, target in items:
        if len(entries) >= limits.max_provenance_entries:
            raise PlistMaterializationFailure(
                PlistMaterializationFailureKind.RESOURCE_LIMIT,
                name="provenance-entries",
            )
        segments = tuple(
            ValuePathSegment(
                ValuePathSegmentKind.SEQUENCE_ELEMENT
                if isinstance(step, int)
                else ValuePathSegmentKind.OBJECT_VALUE,
                step,
            )
            for step in path
        )
        value_path = ValuePath(segments)
        if style is _Style.BINARY:
            facts = document.binary_facts()
            assert facts is not None
            fact = facts.objects[target] if target < len(facts.objects) else None
            if fact is None:
                raise PlistMaterializationFailure(
                    PlistMaterializationFailureKind.FORMATION_FAILED
                )
            origin = MaterializedOrigin(
                snapshot=identity,
                node=authority.node_ref(fact.index, NodeRole.PLIST_VALUE),
                span=fact.span,
                relation=MaterializationRelation.DIRECT,
            )
        else:
            formed = document.formed_xml
            assert formed is not None
            span = formed.value_spans.get(target)
            if span is None:
                raise PlistMaterializationFailure(
                    PlistMaterializationFailureKind.FORMATION_FAILED
                )
            origin = MaterializedOrigin(
                snapshot=identity,
                node=authority.node_ref(target, NodeRole.PLIST_VALUE),
                span=span,
                relation=MaterializationRelation.DIRECT,
            )
        entries.append(
            MaterializationProvenanceEntry(
                input=_Loc.value(value_path),
                outputs=(origin,),
            )
        )
    return MaterializationProvenanceMap.new(entries, document.snapshot_identity(), limits)


