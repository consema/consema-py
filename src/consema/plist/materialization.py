class _ValueKind(enum.Enum):
    DICT = "dict"
    ARRAY = "array"
    STRING = "string"
    INTEGER = "integer"
    REAL = "real"
    BOOLEAN = "boolean"
    DATE = "date"
    DATA = "data"
    UID = "uid"


@dataclass(slots=True)
class _ValueNode:
    kind: _ValueKind
    path: tuple
    entries: list = None  # type: ignore[assignment]  # (key: PlistString, value: _ValueNode)
    elements: list = None  # type: ignore[assignment]
    string: PlistString | None = None
    integer: int | None = None
    real: PlistReal | None = None
    boolean: bool | None = None
    date_seconds: float | None = None
    data: bytes | None = None
    uid: int | None = None

    def __post_init__(self) -> None:
        if self.entries is None:
            self.entries = []
        if self.elements is None:
            self.elements = []


def _decimal_to_f64(decimal: Decimal) -> float | None:
    """Converts one canonical Decimal to its double value
    (materialization.rs:665-668)."""
    try:
        return float(decimal.coefficient) * (10.0 ** decimal.exponent)
    except (OverflowError, ValueError):
        return None


def _leaf_real(value: PortableValue) -> PlistReal | None:
    """One real leaf from the BinaryFloat64 / BinaryFloat32 / Decimal
    spellings (materialization.rs:35-45)."""
    kind = value.kind
    if kind is Kind.BINARY_FLOAT64:
        import struct

        bits = value.as_binary_float64()
        return PlistReal.from_bits(RealWidth.FLOAT64, bits)
    if kind is Kind.BINARY_FLOAT32:
        return PlistReal.from_bits(RealWidth.FLOAT32, value.as_binary_float32())
    if kind is Kind.DECIMAL:
        converted = _decimal_to_f64(value.as_decimal())
        if converted is None:
            return None
        return PlistReal.double(converted)
    return None


def _leaf_seconds(value: PortableValue) -> float | None:
    """One date leaf's exact double seconds from the ``{epoch, seconds}``
    spelling (materialization.rs:32-34)."""
    entries = value.as_object()
    fields = dict(entries)
    epoch = fields.get("epoch")
    seconds = fields.get("seconds")
    if epoch is None or seconds is None:
        return None
    if epoch.kind is not Kind.STRING or epoch.as_string() != _PLIST_EPOCH_SPELLING:
        return None
    if seconds.kind is Kind.BINARY_FLOAT64:
        import struct

        return struct.unpack(">d", struct.pack(">Q", seconds.as_binary_float64()))[0]
    if seconds.kind is Kind.DECIMAL:
        return _decimal_to_f64(seconds.as_decimal())
    return None


def _leaf_hex(value: PortableValue) -> bytes | None:
    """One data leaf from the ``{hex: String}`` spelling; strict lowercase
    or uppercase hex (materialization.rs:36-37)."""
    entries = value.as_object()
    fields = dict(entries)
    hex_value = fields.get("hex")
    if hex_value is None or hex_value.kind is not Kind.STRING:
        return None
    text = hex_value.as_string()
    if len(text) % 2 != 0:
        return None
    try:
        return bytes.fromhex(text)
    except ValueError:
        return None


def _leaf_uid(value: PortableValue) -> int | None:
    entries = value.as_object()
    fields = dict(entries)
    uid = fields.get("uid")
    if uid is None or uid.kind is not Kind.INTEGER:
        return None
    integer = uid.as_integer()
    if not 0 <= integer <= 0xFFFF_FFFF:
        return None
    return integer


def parse_record(value: PortableValue, analyzed: list, depth: int = 0) -> _ValueNode:
    """Parses one ``plist.value-tree@1`` record into the value-node shape
    (materialization.rs:180-660). Every admission gate fails atomically."""
    if depth > 256:
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.RESOURCE_LIMIT, name="depth"
        )
    analyzed.append(("root",))
    if value.kind is not Kind.OBJECT:
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.INVALID_REQUEST,
            detail="record must be an object",
        )
    fields = dict(value.as_object())
    record = fields.get("record")
    root = fields.get("root")
    if record is None or record.kind is not Kind.STRING or record.as_string() != _VALUE_TREE_RECORD:
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.INVALID_REQUEST,
            detail="record identity",
        )
    if root is None:
        raise PlistMaterializationFailure(
            PlistMaterializationFailureKind.INVALID_REQUEST,
            detail="missing root",
        )
    truncate = fields.get("truncate_policy")
    policy = None
    if truncate is not None:
        if truncate.kind is not Kind.STRING or truncate.as_string() != _TRUNCATE_POLICY:
            raise PlistMaterializationFailure(
                PlistMaterializationFailureKind.INVALID_REQUEST,
                detail="truncate policy",
            )
        policy = _TRUNCATE_POLICY
    return _parse_value(root, ("root",), policy, analyzed, depth + 1)


def _parse_value(
    value: PortableValue, path: tuple, truncate: str | None, analyzed: list, depth: int
) -> _ValueNode:
    analyzed.append(path)
    kind = value.kind
    if kind is Kind.ENTRY_MAPPING:
        node = _ValueNode(_ValueKind.DICT, path)
        for position, (key_value, entry_value) in enumerate(value.as_entry_mapping()):
            if key_value.kind is not Kind.STRING:
                raise PlistMaterializationFailure(
                    PlistMaterializationFailureKind.UNREPRESENTABLE,
                    detail="non-string dict key",
                )
            key = PlistString.from_unicode(key_value.as_string())
            child = _parse_value(
                entry_value, path + (position,), truncate, analyzed, depth + 1
            )
            node.entries.append((key, child))
        return node
    if kind is Kind.OBJECT:
        entries = value.as_object()
        fields = dict(entries)
        # An Object whose members are exactly `epoch` + `seconds`, `uid`,
        # or `hex` is the corresponding typed leaf; any other Object is a
        # dictionary (materialization.rs:47-53).
        if set(fields) == {"epoch", "seconds"}:
            seconds = _leaf_seconds(value)
            if seconds is None:
                raise PlistMaterializationFailure(
                    PlistMaterializationFailureKind.UNREPRESENTABLE,
                    detail="date",
                )
            return _ValueNode(_ValueKind.DATE, path, date_seconds=seconds)
        if set(fields) == {"hex"}:
            data = _leaf_hex(value)
            if data is None:
                raise PlistMaterializationFailure(
                    PlistMaterializationFailureKind.UNREPRESENTABLE,
                    detail="data",
                )
            return _ValueNode(_ValueKind.DATA, path, data=data)
        if set(fields) == {"uid"}:
            uid = _leaf_uid(value)
            if uid is None:
                raise PlistMaterializationFailure(
                    PlistMaterializationFailureKind.UNREPRESENTABLE,
                    detail="uid",
                )
            return _ValueNode(_ValueKind.UID, path, uid=uid)
        node = _ValueNode(_ValueKind.DICT, path)
        for position, (name, entry_value) in enumerate(entries):
            child = _parse_value(
                entry_value, path + (position,), truncate, analyzed, depth + 1
            )
            node.entries.append((PlistString.from_unicode(name), child))
        return node
    if kind is Kind.SEQUENCE:
        node = _ValueNode(_ValueKind.ARRAY, path)
        for position, element in enumerate(value.as_sequence()):
            node.elements.append(
                _parse_value(element, path + (position,), truncate, analyzed, depth + 1)
            )
        return node
    if kind is Kind.STRING:
        return _ValueNode(_ValueKind.STRING, path, string=PlistString.from_unicode(value.as_string()))
    if kind is Kind.INTEGER:
        integer = value.as_integer()
        if not -(1 << 63) <= integer <= (1 << 63) - 1:
            raise PlistMaterializationFailure(
                PlistMaterializationFailureKind.UNREPRESENTABLE,
                detail="integer range",
            )
        return _ValueNode(_ValueKind.INTEGER, path, integer=integer)
    if kind in (Kind.BINARY_FLOAT64, Kind.BINARY_FLOAT32, Kind.DECIMAL):
        real = _leaf_real(value)
        if real is None:
            raise PlistMaterializationFailure(
                PlistMaterializationFailureKind.UNREPRESENTABLE,
                detail="real",
            )
        return _ValueNode(_ValueKind.REAL, path, real=real)
    if kind is Kind.BOOLEAN:
        return _ValueNode(_ValueKind.BOOLEAN, path, boolean=value.as_boolean())
    if kind is Kind.BYTES:
        return _ValueNode(_ValueKind.DATA, path, data=value.as_bytes())
    raise PlistMaterializationFailure(
        PlistMaterializationFailureKind.UNREPRESENTABLE,
        detail=kind.value,
    )


